static bool
wmi_cmd_words(uint32_t cmd_id, const uint32_t *w, uint32_t nwords)
{
	return wmi_cmd(cmd_id, w, nwords * 4u);
}

/* ath10k_wmi_tlv_op_gen_pdev_set_param: pdev_id 0, param, value */
static bool
pdev_set_param(uint32_t param, uint32_t value)
{
	uint32_t w[4] = { tlv_hdr(WMI_TLV_TAG_PDEV_SET_PARAM_CMD, 12u), 0u, param, value };
	return wmi_cmd_words(WMI_TLV_PDEV_SET_PARAM_CMDID, w, 4u);
}

static inline bool
svc_has(uint32_t bit)
{
	return bit < 128u && ((gSvc.svc[bit / 32u] >> (bit % 32u)) & 1u) != 0;
}

/* mac.c ath10k_start after ath10k_core_start, in its order: PMF QoS, dynamic bandwidth, burst off (if the firmware
 * has the service), idle power-save config, __ath10k_set_antenna with the board's chains ((1 << num_rf_chains) - 1,
 * wmi.c), ARP access category, ANI on. Not sent, as ath10k does not for this firmware: the probe request OUI (no
 * random MAC), adaptive OCS (service absent), adaptive CCA and BT coex (feature flags absent). */
static const char *
start_params(uint32_t *chains_out)
{
	uint32_t n = gSvc.ev[SR_NUM_RF_CHAINS];
	uint32_t chains = n >= 1u && n <= 4u ? (1u << n) - 1u : 1u;
	*chains_out = chains;
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_PMF_QOS, 1u)) return "PMF QoS";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_DYNAMIC_BW, 1u)) return "dynamic bandwidth";
	if (svc_has(WMI_TLV_SERVICE_BURST) && !pdev_set_param(WMI_TLV_PDEV_PARAM_BURST_ENABLE, 0u)) return "burst";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_IDLE_PS_CONFIG, 1u)) return "idle power save";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_TX_CHAIN_MASK, chains)) return "tx chain mask";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_RX_CHAIN_MASK, chains)) return "rx chain mask";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_ARP_AC_OVERRIDE, 0u)) return "ARP access category";
	if (!pdev_set_param(WMI_TLV_PDEV_PARAM_ANI_ENABLE, 1u)) return "ANI";
	return NULL;
}

/* ath10k_wmi_tlv_op_gen_pdev_set_rd with the board's EEPROM domain (WORC_WORLD 0x6c on this phone: no CTLs) */
static bool
scan_set_regdomain(void)
{
	uint32_t rd = gEepromRd & 0xFFFFu;
	uint32_t w[7] = { tlv_hdr(WMI_TLV_TAG_PDEV_SET_REGDOMAIN_CMD, 24u), 0u, rd, rd, rd, NO_CTL, NO_CTL };
	return wmi_cmd_words(WMI_TLV_PDEV_SET_REGDOMAIN_CMDID, w, 7u);
}

/* ath10k_wmi_tlv_op_gen_scan_chan_list: struct wmi_channel { mhz, band_center_freq1, band_center_freq2,
 * mode | flags, min/max/reg power, classid (0.5 dBm), antenna_max, max_tx_power } per channel */
static bool
scan_chan_list(bool active24)   /* active24: 2.4 GHz channels 1-11 may send probe requests (step 5) */
{
	uint32_t *w = gChanCmd, n = 0;
	w[n++] = tlv_hdr(WMI_TLV_TAG_SCAN_CHAN_LIST_CMD, 4u);
	w[n++] = SCAN_NCHAN;
	w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_STRUCT, SCAN_NCHAN * 28u);
	for (uint32_t i = 0; i < SCAN_NCHAN; i++) {
		uint32_t mhz = kScanMhz[i];
		bool g5 = mhz > 5000u, dfs = (mhz >= 5260u && mhz <= 5320u) || (mhz >= 5500u && mhz <= 5700u);
		bool passive = !(active24 && mhz <= 2462u);
		w[n++] = tlv_hdr(WMI_TLV_TAG_CHANNEL, 24u);
		w[n++] = mhz;
		w[n++] = mhz;
		w[n++] = 0u;
		w[n++] = (g5 ? WMI_MODE_11A : WMI_MODE_11G) | (passive ? WMI_CHAN_FLAG_PASSIVE : 0u) | WMI_CHAN_FLAG_ALLOW_HT |
		    (g5 ? WMI_CHAN_FLAG_ALLOW_VHT : 0u) | (dfs ? WMI_CHAN_FLAG_DFS : 0u);
		w[n++] = (40u << 8) | (40u << 16);   /* max power, reg power: 20 dBm */
		w[n++] = 40u << 8;                    /* max tx power */
	}
	return wmi_cmd_words(WMI_TLV_SCAN_CHAN_LIST_CMDID, w, n);
}

static bool
vdev_create(uint32_t id)
{
	uint32_t w[6] = { tlv_hdr(WMI_TLV_TAG_VDEV_CREATE_CMD, 20u), id, WMI_VDEV_TYPE_STA, 0u, 0u, 0u };
	memcpy(&w[4], gMac, 6u);
	return wmi_cmd_words(WMI_TLV_VDEV_CREATE_CMDID, w, 6u);
}

static bool
vdev_delete(uint32_t id)
{
	uint32_t w[2] = { tlv_hdr(WMI_TLV_TAG_VDEV_DELETE_CMD, 4u), id };
	return wmi_cmd_words(WMI_TLV_VDEV_DELETE_CMDID, w, 2u);
}

/* HTT rx ring (htt_rx.c ath10k_htt_rx_alloc + ath10k_htt_rx_ring_fill_n, htt_tx.c ath10k_htt_send_rx_ring_cfg_32 +
 * ath10k_htt_h2t_aggr_cfg_msg). ath10k hands the firmware this ring before anything else runs; the firmware
 * receives nothing without it. Ring entries are the 32-bit addresses of 2 KB buffers; alloc_idx (host memory the
 * firmware reads) is how far the host has posted. Each buffer starts with struct htt_rx_desc_v1 (QCA6174 uses
 * qca988x_rx_desc_ops): attention at 4, msdu_start at 24, ppdu_start at 84, rx_hdr_status at 236, payload at 300. */
#define HTT_H2T_MSG_TYPE_RX_RING_CFG      2u
#define HTT_H2T_MSG_TYPE_AGGR_CFG         5u
#define HTT_T2H_MSG_TYPE_RX_IND           1u
#define HTT_RX_RING_SIZE                  256u      /* entries, a power of two */
#define HTT_RX_FILL                       127u      /* buffers posted: ath10k's size / 2 - 1 */
#define HTT_RX_BUF_SIZE                   2048u
#define HTT_RX_RING_OFF                   (HTT_RX_FILL * HTT_RX_BUF_SIZE)
#define HTT_RX_IDX_OFF                    (HTT_RX_RING_OFF + 4u * HTT_RX_RING_SIZE)
#define HTT_RX_BLOCK                      0x40000u  /* 256 KB: 127 buffers, the ring, alloc_idx */
#define RXD_ATTENTION                     4u
#define RXD_MSDU_START                    24u
#define RXD_RSSI_COMB                     100u      /* ppdu_start.rssi_comb: dB over the noise floor */
#define RXD_HDR_STATUS                    236u
#define RXD_HDR_STATUS_LEN                64u
#define RXD_PAYLOAD                       300u
#define RX_ATTN_MGMT                      (1u << 8)
#define RX_ATTN_CTRL                      (1u << 9)
#define RX_ATTN_FCS_ERR                   (1u << 30)
#define RX_ATTN_MSDU_DONE                 (1u << 31)
#define WMI_TLV_CHAN_INFO_EVENTID         0x4002u
#define WMI_TLV_TAG_CHAN_INFO_EVENT       38u
#define WMI_CHAN_INFO_FLAG_COMPLETE       1u

/* struct htt_rx_ring_rx_desc_offsets for htt_rx_desc_v1, in 4-byte words: mac80211 header, msdu payload,
 * ppdu start/end, mpdu start/end, msdu start/end, attention, frag info */
static void add_frame(const uint8_t *f, uint32_t flen, uint32_t chan, int32_t dbm, bool from_ring);
/* steps 5 and 6: management frames other than beacons (WMI or the ring) and data frames (the ring) */
static void (*gMgmtHook)(const uint8_t *f, uint32_t len);
static void (*gDataHook)(const uint8_t *f, uint32_t len);
static uint32_t gRingData;

static_assert(HTT_RX_IDX_OFF + 4u <= HTT_RX_BLOCK, "the HTT rx block holds the buffers, the ring and alloc_idx");

static const uint16_t kRxDescOffsets[10] = { 59, 75, 21, 31, 3, 20, 6, 10, 1, 2 };

static uint8_t *gRxPool;
static uint32_t gRxPoolPhys, gRxAlloc;
/* Buffers, not ring positions, are tracked: posted (the chip owns it) and in which order (seq). A finished buffer is
 * found by MSDU_DONE (scan beacons: the firmware indicates nothing) or named by an in-order indication (this
 * firmware's rx full reorder mode, with an rx descriptor or, offloaded, a short header); either way it is handled
 * once and posted again at the ring's end. One the chip never finishes cannot hold up the others. */
static bool gBufPosted[HTT_RX_FILL];
static uint32_t gBufSeq[HTT_RX_FILL], gPostSeq;
static uint32_t gInOrdInd, gInOrdFrames, gInOrdOffload, gInOrdBad;
static uint32_t gRingFrames, gRingMgmt, gRingCtrl, gRingFcs, gRingBeacons, gHttRxInd, gHttOther;
static uint32_t gScanMhz, gChanInfos, gChanHeard, gChanBusy, gChanInfoLines;
static int32_t gNfMin = 1000, gNfMax = -1000;
static uint32_t gCiMhz, gCiRxClear, gCiCycles, gCiRxFrame;   /* the last "start of dwell" chan info */

static inline void
put16(uint8_t *p, uint32_t v)
{
	p[0] = (uint8_t)v;
	p[1] = (uint8_t)(v >> 8);
}

static inline void
put32(uint8_t *p, uint32_t v)
{
	put16(p, v);
	put16(p + 2, v >> 16);
}

static inline uint32_t
mhz_to_chan(uint32_t mhz)
{
	return mhz >= 5000u ? (mhz - 5000u) / 5u : mhz >= 2407u ? (mhz - 2407u) / 5u : 0u;
}

static bool
htt_rx_setup(char *res, size_t len)
{
	if (gRxPool == NULL) {
		IOPhysicalAddress phys = 0;
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
		void *cached = IOMallocContiguous(HTT_RX_BLOCK, 4096, &phys);
#pragma clang diagnostic pop
		if (cached == NULL || phys == 0 || (uint64_t)phys + HTT_RX_BLOCK > 0x100000000ULL ||
		    !clear_of_window(phys, HTT_RX_BLOCK)) {
			snprintf(res, len, "STEP 4 FAIL: no usable %u KB for the HTT rx ring below 4 GB (phys %llx)",
			    HTT_RX_BLOCK / 1024u, (unsigned long long)phys);
			return false;
		}
		cache_flush(cached, HTT_RX_BLOCK);   /* the cacheable alias is never touched again */
		gRxPool = (uint8_t *)ml_io_map_wcomb((vm_offset_t)phys, HTT_RX_BLOCK);
		if (gRxPool == NULL) {
			snprintf(res, len, "STEP 4 FAIL: no non-cacheable mapping for the HTT rx ring at %08x", (uint32_t)phys);
			return false;
		}
		gRxPoolPhys = (uint32_t)phys;
	}
	/* ath10k_htt_rx_ring_refill: buffers with cleared descriptors, then alloc_idx */
	bzero(gRxPool, HTT_RX_BLOCK);
	for (uint32_t i = 0; i < HTT_RX_FILL; i++) {
		put32(gRxPool + HTT_RX_RING_OFF + 4u * i, gRxPoolPhys + i * HTT_RX_BUF_SIZE);
		gBufPosted[i] = true;
		gBufSeq[i] = i;
	}
	gPostSeq = HTT_RX_FILL;
	gRxAlloc = HTT_RX_FILL;
	put32(gRxPool + HTT_RX_IDX_OFF, gRxAlloc);
	dma_fence();

	/* RX_RING_CFG: htt_cmd_hdr (1), htt_rx_ring_setup_hdr (num_rings 1, rsvd 2), htt_rx_ring_setup_ring32 (36) */
	uint8_t m[40];
	bzero(m, sizeof(m));
	m[0] = HTT_H2T_MSG_TYPE_RX_RING_CFG;
	m[1] = 1u;
	put32(m + 4, gRxPoolPhys + HTT_RX_IDX_OFF);    /* fw_idx_shadow_reg_paddr = alloc_idx */
	put32(m + 8, gRxPoolPhys + HTT_RX_RING_OFF);   /* rx_ring_base_paddr */
	put16(m + 12, HTT_RX_RING_SIZE);
	put16(m + 14, HTT_RX_BUF_SIZE);
	put16(m + 16, 0xFFFFu);                         /* every HTT_RX_RING_FLAGS_* ath10k sets */
	put16(m + 18, gRxAlloc);                        /* fw_idx_init_val */
	for (uint32_t i = 0; i < 10u; i++) {
		put16(m + 20 + 2u * i, kRxDescOffsets[i]);
	}
	if (!htc_send(gEpHtt, &gCe4, OFF_HTT_TX, HTT_TX_MAX, m, sizeof(m), false)) {
		snprintf(res, len, "%s", "STEP 4 FAIL: HTT rx ring config could not be sent");
		return false;
	}
	/* ATH10K_HTT_MAX_NUM_AMPDU_DEFAULT 64, ATH10K_HTT_MAX_NUM_AMSDU_DEFAULT 3 */
	uint8_t a[3] = { HTT_H2T_MSG_TYPE_AGGR_CFG, 64u, 3u };
	if (!htc_send(gEpHtt, &gCe4, OFF_HTT_TX, HTT_TX_MAX, a, sizeof(a), false)) {
		snprintf(res, len, "%s", "STEP 4 FAIL: HTT aggregation config could not be sent");
		return false;
	}
	A_LOG("HTT rx ring: %u entries at %08x, %u buffers of %u bytes posted, alloc_idx at %08x; aggregation 64/3",
	    HTT_RX_RING_SIZE, gRxPoolPhys + HTT_RX_RING_OFF, HTT_RX_FILL, HTT_RX_BUF_SIZE, gRxPoolPhys + HTT_RX_IDX_OFF);
	return true;
}

/* One received frame in buffer b with its rx descriptor: counted, beacons parsed, the rest to the join hooks */
static void
rx_frame(uint32_t b, uint32_t mlen)
{
	uint8_t *d = gRxPool + b * HTT_RX_BUF_SIZE;
	uint32_t attn = le32(d + RXD_ATTENTION);
	gRingFrames++;
	const uint8_t *h = d + RXD_HDR_STATUS, *pl = d + RXD_PAYLOAD;
	if (gRingFrames <= 4u) {
		A_LOG("rx ring frame %u (buffer %u): attention %08x msdu length %u rssi %u | header %02x %02x %02x %02x "
		    "%02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x | payload %02x %02x %02x %02x", gRingFrames,
		    b, attn, mlen, d[RXD_RSSI_COMB], h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7], h[8], h[9], h[10],
		    h[11], h[12], h[13], h[14], h[15], pl[0], pl[1], pl[2], pl[3]);
	}
	if (attn & RX_ATTN_FCS_ERR) {
		gRingFcs++;
	} else if (attn & RX_ATTN_CTRL) {
		gRingCtrl++;
	} else if (attn & RX_ATTN_MGMT) {
		gRingMgmt++;
		int32_t dbm = (int32_t)d[RXD_RSSI_COMB] + ATH10K_DEFAULT_NOISE_FLOOR;
		uint32_t chan = mhz_to_chan(gScanMhz);
		/* the whole frame in the payload (raw), else the first 64 bytes in rx_hdr_status */
		bool whole = mlen >= 24u && mlen <= HTT_RX_BUF_SIZE - RXD_PAYLOAD;
		if (whole && mlen >= 36u && (pl[0] == 0x80u || pl[0] == 0x50u)) {
			add_frame(pl, mlen, chan, dbm, true);
		} else if (!whole && (h[0] == 0x80u || h[0] == 0x50u)) {
			add_frame(h, RXD_HDR_STATUS_LEN, chan, dbm, true);
		} else if (whole && gMgmtHook != NULL) {
			gMgmtHook(pl, mlen);
		}
	} else {
		gRingData++;
		if (gDataHook != NULL && mlen >= 24u && mlen <= HTT_RX_BUF_SIZE - RXD_PAYLOAD) {
			gDataHook(pl, mlen);
		}
	}
}

/* buffer b back to the chip, at the ring's end */
static void
rx_repost(uint32_t b)
{
	uint8_t *d = gRxPool + b * HTT_RX_BUF_SIZE;
	bzero(d, RXD_PAYLOAD + 64u);   /* the descriptor (attention included) and the start of the payload */
	put32(gRxPool + HTT_RX_RING_OFF + 4u * gRxAlloc, gRxPoolPhys + b * HTT_RX_BUF_SIZE);
	gRxAlloc = (gRxAlloc + 1u) & (HTT_RX_RING_SIZE - 1u);
	gBufPosted[b] = true;
	gBufSeq[b] = gPostSeq++;
	dma_fence();
	put32(gRxPool + HTT_RX_IDX_OFF, gRxAlloc);
	dma_fence();
}

/* Every posted buffer the chip has finished (MSDU_DONE), oldest posting first */
static void
rx_ring_poll(void)
{
	if (gRxPool == NULL) {
		return;
	}
	uint32_t done[HTT_RX_FILL], nd = 0;
	for (uint32_t b = 0; b < HTT_RX_FILL; b++) {
		if (gBufPosted[b] && (le32(gRxPool + b * HTT_RX_BUF_SIZE + RXD_ATTENTION) & RX_ATTN_MSDU_DONE) != 0) {
			uint32_t j = nd++;
			for (; j > 0 && gBufSeq[done[j - 1u]] > gBufSeq[b]; j--) {
				done[j] = done[j - 1u];
			}
			done[j] = b;
		}
	}
	if (nd > 0) {
		dma_fence();   /* the attention word before the rest of the buffer */
	}
	for (uint32_t i = 0; i < nd; i++) {
		uint32_t b = done[i];
		gBufPosted[b] = false;
		rx_frame(b, le32(gRxPool + b * HTT_RX_BUF_SIZE + RXD_MSDU_START) & 0x3FFFu);
		rx_repost(b);
	}
}

/* HTT_T2H_MSG_TYPE_RX_IN_ORD_PADDR_IND (htt_rx.c ath10k_htt_rx_in_ord_ind, ath10k_htt_rx_pop_paddr32_list):
 * info (tid, offload 0x20), peer, vdev, msdu count, then { paddr, length, fw_desc } per buffer. Offloaded frames
 * have no rx descriptor but struct htt_rx_offload_msdu { len, peer, vdev, tid, fw_desc } and the native wifi
 * frame right after it (ath10k_htt_rx_h_rx_offload). */
static void
rx_inord(void)
{
	if (gRxLen < 8u || gRxPool == NULL) {
		return;
	}
	uint32_t info = gRx[1], count = le16(gRx + 6);
	bool offload = (info & 0x20u) != 0;
	if (gInOrdInd <= 3u) {
		A_LOG("HTT in-order rx indication: info %02x (tid %u%s%s), peer %u vdev %u, %u buffers, first %08x (%u bytes)",
		    info, info & 0x1Fu, offload ? ", offloaded" : "", (info & 0x40u) ? ", fragment" : "", le16(gRx + 2), gRx[4],
		    count, gRxLen >= 16u ? le32(gRx + 8) : 0u, gRxLen >= 16u ? le16(gRx + 12) : 0u);
	}
	for (uint32_t i = 0; i < count && 8u + 8u * i + 8u <= gRxLen; i++) {
		uint32_t pa = le32(gRx + 8 + 8u * i), len = le16(gRx + 12 + 8u * i);
		uint32_t off = pa - gRxPoolPhys, b = off / HTT_RX_BUF_SIZE;
		if (pa < gRxPoolPhys || b >= HTT_RX_FILL || off % HTT_RX_BUF_SIZE != 0 || !gBufPosted[b]) {
			gInOrdBad++;   /* not one of ours, or already handled when its MSDU_DONE was seen */
			continue;
		}
		const uint8_t *d = gRxPool + b * HTT_RX_BUF_SIZE;
		dma_fence();
		gBufPosted[b] = false;
		gInOrdFrames++;
		if (offload) {
			uint32_t olen = le16(d);
			gInOrdOffload++;
			gRingData++;
			if (gDataHook != NULL && olen >= 24u && olen <= HTT_RX_BUF_SIZE - 7u) {
				gDataHook(d + 7, olen);
			}
		} else if (le32(d + RXD_ATTENTION) & RX_ATTN_MSDU_DONE) {
			rx_frame(b, len);
		} else {
			gInOrdBad++;
		}
		rx_repost(b);
	}
}

/* HTT messages (steps 4-6): defined with the join code below */
static void on_htt_msg(void);

/* struct wmi_tlv_chan_info_event: err_code, freq, cmd_flags, noise_floor, rx_clear_count, cycle_count,
 * chan_tx_pwr_range, chan_tx_pwr_tp, rx_frame_count, my_bss_rx_cycle_count, ... One at the start of each dwell
 * and one at its end (COMPLETE); the counters are free-running, so the dwell is the difference. */
static void
on_chan_info(void)
{
	const uint8_t *e = wmi_find(WMI_TLV_TAG_CHAN_INFO_EVENT, 36u);
	if (e == NULL) {
		other_msg();
		return;
	}
	gChanInfos++;
	uint32_t err = le32(e), mhz = le32(e + 4), flags = le32(e + 8);
	int32_t nf = (int32_t)le32(e + 12);
	uint32_t rx_clear = le32(e + 16), cycles = le32(e + 20), rx_frame = le32(e + 32);
	if ((flags & WMI_CHAN_INFO_FLAG_COMPLETE) == 0) {
		gCiMhz = mhz;
		gCiRxClear = rx_clear;
		gCiCycles = cycles;
		gCiRxFrame = rx_frame;
		return;
	}
	bool paired = gCiMhz == mhz;
	uint32_t dc = paired ? cycles - gCiCycles : cycles, dbusy = paired ? rx_clear - gCiRxClear : rx_clear;
	uint32_t drx = paired ? rx_frame - gCiRxFrame : rx_frame;
	gCiMhz = 0;
	if (nf < gNfMin) {
		gNfMin = nf;
	}
	if (nf > gNfMax) {
		gNfMax = nf;
	}
	if (drx != 0) {
		gChanHeard++;
	}
	if (dbusy != 0) {
		gChanBusy++;
	}
	uint32_t pb = dc ? (uint32_t)((uint64_t)dbusy * 100u / dc) : 0u, pr = dc ? (uint32_t)((uint64_t)drx * 100u / dc) : 0u;
	if (gChanInfoLines++ < SCAN_NCHAN) {
		A_LOG("channel %3u (%u MHz): noise floor %d dBm, busy %u%%, receiving %u%% of %u cycles%s%s", mhz_to_chan(mhz),
		    mhz, nf, pb, pr, dc, paired ? "" : " (no start event)", err ? " (error)" : "");
	}
}

/* ath10k_wmi_start_scan_init + ath10k_hw_scan + ath10k_wmi_tlv_op_gen_start_scan. Passive: every channel, no
 * SSIDs (step 4). Directed (step 5): 2.4 GHz channels 1-13 only, probe requests for the configured network's name
 * with our rates (channels 12 and 13 stay passive: the channel list keeps them so). */
#define SCAN_N24 13u
static const uint8_t kProbeIes[16] = { 1, 8, 0x82, 0x84, 0x8B, 0x96, 0x0C, 0x12, 0x18, 0x24, 50, 4, 0x30, 0x48, 0x60, 0x6C };
static const uint8_t *gProbeSsid;
static uint32_t gProbeSsidLen;

static bool
scan_start(uint32_t round, bool directed)
{
	uint32_t *w = gScanCmd, n = 0, nchan = directed ? SCAN_N24 : SCAN_NCHAN;
	w[n++] = tlv_hdr(WMI_TLV_TAG_START_SCAN_CMD, 100u);
	w[n++] = WMI_HOST_SCAN_ID_PREFIX | (2u * round);        /* scan_id (ATH10K_SCAN_ID) */
	w[n++] = WMI_HOST_SCAN_ID_PREFIX | (2u * round + 1u);   /* scan_req_id */
	w[n++] = 0u;                                  /* vdev_id */
	w[n++] = 1u;                                  /* WMI_SCAN_PRIORITY_LOW */
	w[n++] = WMI_SCAN_EVENT_STARTED | WMI_SCAN_EVENT_COMPLETED | WMI_SCAN_EVENT_BSS_CHANNEL |
	    WMI_SCAN_EVENT_FOREIGN_CHANNEL | WMI_SCAN_EVENT_FOREIGN_CHANNEL_EXIT | WMI_SCAN_EVENT_DEQUEUED;
	w[n++] = directed ? 100u : 50u;               /* dwell active: time for the answers and their retries */
	w[n++] = 150u;                                /* dwell passive */
	w[n++] = 50u;                                 /* min rest */
	w[n++] = 500u;                                /* max rest */
	w[n++] = 0u;                                  /* repeat probe */
	w[n++] = 0u;                                  /* probe spacing */
	w[n++] = 0u;                                  /* idle */
	w[n++] = 20000u;                              /* max scan time */
	w[n++] = 5u;                                  /* probe delay */
	/* the TLV firmware inverts WMI_SCAN_FILTER_PROBE_REQ (ath10k's FIXME) */
	w[n++] = (WMI_SCAN_CHAN_STAT_EVENT | (directed ? 0u : WMI_SCAN_FLAG_PASSIVE)) ^ WMI_SCAN_FILTER_PROBE_REQ;
	w[n++] = 0u;                                  /* burst duration */
	w[n++] = nchan;
	w[n++] = 1u;                                  /* num_bssids: the broadcast one */
	w[n++] = directed ? 1u : 0u;                  /* num_ssids */
	w[n++] = directed ? sizeof(kProbeIes) : 0u;   /* ie_len */
	w[n++] = 3u;                                  /* num_probes */
	w[n++] = 0u; w[n++] = 0u;                     /* mac_addr */
	w[n++] = 0u; w[n++] = 0u;                     /* mac_mask */
	w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_UINT32, nchan * 4u);
	for (uint32_t i = 0; i < nchan; i++) {
		w[n++] = kScanMhz[i];
	}
	if (directed) {
		w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_FIXED_STRUCT, 36u);   /* struct wmi_ssid: length, 32 bytes */
		uint8_t ssid[36];
		bzero(ssid, sizeof(ssid));
		put32(ssid, gProbeSsidLen);
		memcpy(ssid + 4, gProbeSsid, gProbeSsidLen);
		memcpy(&w[n], ssid, sizeof(ssid));
		n += 9u;
	} else {
		w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_FIXED_STRUCT, 0u);   /* SSIDs */
	}
	w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_FIXED_STRUCT, 8u);   /* BSSIDs: ff:ff:ff:ff:ff:ff */
	w[n++] = 0xFFFFFFFFu;
	w[n++] = 0x0000FFFFu;
	if (directed) {
		w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_BYTE, sizeof(kProbeIes));   /* extra IEs: supported, extended rates */
		memcpy(&w[n], kProbeIes, sizeof(kProbeIes));
		n += sizeof(kProbeIes) / 4u;
	} else {
		w[n++] = tlv_hdr(WMI_TLV_TAG_ARRAY_BYTE, 0u);
	}
	return wmi_cmd_words(WMI_TLV_START_SCAN_CMDID, w, n);
}

static const char *
scan_event_name(uint32_t t)
{
	switch (t) {
	case WMI_SCAN_EVENT_STARTED: return "started";
	case WMI_SCAN_EVENT_COMPLETED: return "completed";
	case WMI_SCAN_EVENT_BSS_CHANNEL: return "back on the home channel";
	case WMI_SCAN_EVENT_FOREIGN_CHANNEL: return "on a channel";
	case WMI_SCAN_EVENT_DEQUEUED: return "dequeued";
	case WMI_SCAN_EVENT_PREEMPTED: return "preempted";
	case WMI_SCAN_EVENT_START_FAILED: return "start failed";
	case WMI_SCAN_EVENT_FOREIGN_CHANNEL_EXIT: return "left a channel";
	default: return "other";
	}
}

static void
on_scan_event(void)
{
	const uint8_t *e = wmi_find(WMI_TLV_TAG_SCAN_EVENT, 24u);
	if (e == NULL) {
		A_LOG("%s", "scan event without its TLV");
		return;
	}
	uint32_t type = le32(e), reason = le32(e + 4), freq = le32(e + 8);
	if (type == WMI_SCAN_EVENT_FOREIGN_CHANNEL) {
		rx_ring_poll();   /* frames heard on the previous channel keep its number */
		gScanForeign++;
		gScanMhz = freq;
		return;
	}
	if (type == WMI_SCAN_EVENT_FOREIGN_CHANNEL_EXIT || type == WMI_SCAN_EVENT_BSS_CHANNEL) {
		return;
	}
	A_LOG("scan event: %s (type %x, reason %u, freq %u, scan id %x)", scan_event_name(type), type, reason, freq,
	    le32(e + 16));
	if (type == WMI_SCAN_EVENT_STARTED) {
		gScanStarted = true;
	} else if (type == WMI_SCAN_EVENT_COMPLETED || type == WMI_SCAN_EVENT_START_FAILED ||
	    type == WMI_SCAN_EVENT_PREEMPTED) {
		gScanDone = true;
		gScanEvent = type;
		gScanReason = reason;
	}
}

/* One beacon or probe response, from WMI MGMT_RX or from the HTT rx ring: BSSID, SSID, channel, strongest signal,
 * security. f is the 802.11 frame (flen bytes); chan the channel number the firmware or the scan reported. */
static void
add_frame(const uint8_t *f, uint32_t flen, uint32_t chan, int32_t dbm, bool from_ring)
{
	/* 24-byte header, then timestamp (8), beacon interval (2), capabilities (2), elements */
	if (flen < 36u || (f[0] != 0x80u && f[0] != 0x50u)) {
		if (!from_ring) {
			gScanDropped++;
		}
		return;
	}
	if (from_ring) {
		gRingBeacons++;
	}
	const uint8_t *bssid = f + 16;
	uint32_t cap = le16(f + 34);
	bool rsn = false, wpa = false, wmm = false, ht = false;
	uint32_t ssid_len = 0, ds = 0, rsn_len = 0, rates_len = 0, xrates_len = 0;
	const uint8_t *ssid = NULL, *rsn_ie = NULL, *rates = NULL, *xrates = NULL;
	for (uint32_t o = 36u; o + 2u <= flen;) {
		uint32_t id = f[o], l = f[o + 1u];
		if (o + 2u + l > flen) {
			break;
		}
		const uint8_t *p = f + o + 2u;
		if (id == 0u && ssid == NULL) {
			ssid = p;
			ssid_len = l > 32u ? 32u : l;
		} else if (id == 1u && rates == NULL) {
			rates = p;
			rates_len = l > 8u ? 8u : l;
		} else if (id == 3u && l >= 1u) {
			ds = p[0];
		} else if (id == 45u) {
			ht = true;
		} else if (id == 48u && rsn_ie == NULL) {
			rsn = true;
			rsn_ie = p;
			rsn_len = l > 64u ? 64u : l;
		} else if (id == 50u && xrates == NULL) {
			xrates = p;
			xrates_len = l > 16u ? 16u : l;
		} else if (id == 221u && l >= 4u && p[0] == 0x00u && p[1] == 0x50u && p[2] == 0xF2u && p[3] == 1u) {
			wpa = true;
		} else if (id == 221u && l >= 5u && p[0] == 0x00u && p[1] == 0x50u && p[2] == 0xF2u && p[3] == 2u &&
		    p[4] <= 1u) {
			wmm = true;   /* WMM information or parameter element */
		}
		o += 2u + l;
	}
	struct bss *b = NULL;
	for (uint32_t i = 0; i < gNumBss; i++) {
		if (memcmp(gBss[i].bssid, bssid, 6u) == 0) {
			b = &gBss[i];
			break;
		}
	}
	if (b == NULL) {
		if (gNumBss >= SCAN_MAX_BSS) {
			return;
		}
		b = &gBss[gNumBss++];
		bzero(b, sizeof(*b));
		memcpy(b->bssid, bssid, 6u);
		b->dbm = dbm;
	}
	b->frames++;
	if (f[0] == 0x50u && memcmp(f + 4, gMac, 6u) == 0) {
		b->probed = true;
	}
	if (dbm > b->dbm) {
		b->dbm = dbm;
	}
	b->chan = ds != 0 ? ds : chan;
	b->mhz = b->chan >= 1u && b->chan <= 13u ? 2407u + 5u * b->chan : b->chan == 14u ? 2484u : 5000u + 5u * b->chan;
	b->sec = rsn ? "WPA2" : wpa ? "WPA" : (cap & 0x10u) ? "WEP" : "open";
	if (ssid != NULL && ssid_len > 0 && (!b->have_ies || flen > RXD_HDR_STATUS_LEN)) {
		/* a whole frame (not the 64-byte header copy) refreshes what joining uses */
		b->have_ies = flen > RXD_HDR_STATUS_LEN || !b->have_ies;
		b->cap = (uint16_t)cap;
		b->bintval = (uint16_t)le16(f + 32);
		b->rsn_len = (uint8_t)rsn_len;
		if (rsn_len) {
			memcpy(b->rsn, rsn_ie, rsn_len);
		}
		b->rates_len = (uint8_t)rates_len;
		if (rates_len) {
			memcpy(b->rates, rates, rates_len);
		}
		b->xrates_len = (uint8_t)xrates_len;
		if (xrates_len) {
			memcpy(b->xrates, xrates, xrates_len);
		}
		b->wmm = wmm;
		b->ht = ht;
	}
	if (ssid != NULL && ssid_len > 0 && b->ssid_len == 0) {
		bool hidden = true;
		for (uint32_t i = 0; i < ssid_len; i++) {
			hidden = hidden && ssid[i] == 0;
		}
		if (!hidden) {
			memcpy(b->raw_ssid, ssid, ssid_len);
			for (uint32_t i = 0; i < ssid_len; i++) {
				b->ssid[i] = (ssid[i] >= 0x20u && ssid[i] < 0x7Fu) ? (char)ssid[i] : '?';
			}
			b->ssid[ssid_len] = 0;
			b->ssid_len = (uint8_t)ssid_len;
		}
	}
}

/* ath10k_wmi_event_mgmt_rx */
static void
on_mgmt_rx(void)
{
	struct tlv_it it = { gRx + 4, gRxLen - 4u };
	uint32_t tag = 0, tl = 0, flen = 0;
	const uint8_t *v = NULL, *hdr = NULL, *f = NULL;
	while (tlv_next(&it, &tag, &tl, &v) == 1) {
		if (tag == WMI_TLV_TAG_MGMT_RX_HDR && tl >= 24u && hdr == NULL) {
			hdr = v;
		} else if (tag == WMI_TLV_TAG_ARRAY_BYTE && f == NULL) {
			f = v;
			flen = tl;
		}
	}
	gScanFrames++;
	if (hdr == NULL || f == NULL) {
		gScanDropped++;
		return;
	}
	uint32_t chan = le32(hdr), snr = le32(hdr + 4), buf_len = le32(hdr + 16), status = le32(hdr + 20);
	if (buf_len < flen) {
		flen = buf_len;
	}
	if (status & WMI_RX_STATUS_ERR_CRC) {
		gScanDropped++;
		return;
	}
	if (flen >= 24u && f[0] != 0x80u && f[0] != 0x50u && gMgmtHook != NULL) {
		gMgmtHook(f, flen);
		return;
	}
	add_frame(f, flen, chan, (int32_t)snr + ATH10K_DEFAULT_NOISE_FLOOR, false);
}

static bool
run4(char *res, size_t len)
{
	gStep = "4";
	gNumBss = gScanFrames = gScanDropped = gScanForeign = 0;
	gScanStarted = gScanDone = false;
	uint32_t t0 = ms_since_power_on();

	/* ath10k_core_start: ath10k_core_reset_rx_filter (QCA6174 hw3.2 hw_filter_reset_required: a station vdev
	 * created and deleted, then a WMI barrier), ath10k_htt_rx_ring_refill, ath10k_htt_setup (rx ring config,
	 * aggregation config); then ath10k_regd_update (regdomain, channel list), ath10k_add_interface, ath10k_hw_scan */
	const char *echo = "not tried";
	bool ok = vdev_create(0u) && vdev_delete(0u);
	if (ok) {
		echo = wmi_echo(1000u);
	}
	if (ok && !htt_rx_setup(res, len)) {
		return false;
	}
	uint32_t chains = 0;
	const char *bad = ok ? start_params(&chains) : NULL;
	if (bad != NULL) {
		snprintf(res, len, "STEP 4 FAIL: the %s setting could not be sent", bad);
		return false;
	}
	ok = ok && scan_set_regdomain() && scan_chan_list(false) && vdev_create(0u) && scan_start(0u, false);
	A_LOG("rx filter reset (barrier echo %s), start settings (chain mask %x, ANI on, burst %s), regdomain %x, %u "
	    "channels (all passive), station interface with the chip's MAC; scan %s", echo, chains,
	    svc_has(WMI_TLV_SERVICE_BURST) ? "off" : "not offered", gEepromRd & 0xFFFFu, SCAN_NCHAN,
	    ok ? "requested" : "NOT requested");
	if (!ok) {
		snprintf(res, len, "%s", "STEP 4 FAIL: a scan setup command could not be sent (see the lines above)");
		return false;
	}

	/* events until the scan completes: 37 channels x 150 ms dwell is about 6 s; 25 s at most */
	for (uint32_t t = 0; t < 25000u && !gScanDone; t++) {
		int r;
		for (int k = 0; k < 64 && (r = htc_rx_one()) != 0; k++) {
			if (r != 2) {
				continue;
			}
			uint32_t id = msg_id();
			if (gRxEid == gEpWmi && id == WMI_TLV_MGMT_RX_EVENTID) {
				on_mgmt_rx();
			} else if (gRxEid == gEpWmi && id == WMI_TLV_SCAN_EVENTID) {
				on_scan_event();
			} else if (gRxEid == gEpWmi && id == WMI_TLV_CHAN_INFO_EVENTID) {
				on_chan_info();
			} else if (gRxEid == gEpHtt) {
				on_htt_msg();
			} else {
				other_msg();
			}
		}
		rx_ring_poll();
		if (t % 10u == 0 && fw_down("the scan", res, len)) {
			dump_dbglog();
			return false;
		}
		IOSleep(1);
	}
	rx_ring_poll();
	uint32_t took = ms_since_power_on() - t0;
	A_LOG("scan: %s after %u ms, %u channel visits, %u frames over WMI (%u not beacons or damaged), %u networks",
	    gScanDone ? scan_event_name(gScanEvent) : "NOT finished", took, gScanForeign, gScanFrames, gScanDropped, gNumBss);
	A_LOG("rx ring: %u frames (%u management, %u control, %u bad FCS, %u beacons parsed), %u HTT rx indications, %u "
	    "other HTT messages", gRingFrames, gRingMgmt, gRingCtrl, gRingFcs, gRingBeacons, gHttRxInd, gHttOther);
	A_LOG("radio: %u channel reports (%u channels), noise floor %d..%d dBm, busy on %u channels, receiving on %u",
	    gChanInfos, gChanInfoLines, gChanInfoLines ? gNfMin : 0, gChanInfoLines ? gNfMax : 0, gChanBusy, gChanHeard);

	/* strongest first */
	for (uint32_t i = 1; i < gNumBss; i++) {
		struct bss x = gBss[i];
		uint32_t j = i;
		for (; j > 0 && gBss[j - 1u].dbm < x.dbm; j--) {
			gBss[j] = gBss[j - 1u];
		}
		gBss[j] = x;
	}
	for (uint32_t i = 0; i < gNumBss; i++) {
		const struct bss *b = &gBss[i];
		A_LOG("network %2u: %-32s ch %3u %4d dBm %-4s %3u frames, BSSID %02x:%02x:%02x:%02x:%02x:%02x", i + 1u,
		    b->ssid_len ? b->ssid : "(hidden)", b->chan, b->dbm, b->sec, b->frames, b->bssid[0], b->bssid[1],
		    b->bssid[2], b->bssid[3], b->bssid[4], b->bssid[5]);
	}
	if (!gScanStarted && !gScanDone) {
		snprintf(res, len, "STEP 4 FAIL: the firmware never started the scan (%u frames, fw indicator %08x)", gScanFrames,
		    brd(Q_FW_INDICATOR));
		dump_dbglog();
		return false;
	}
	if (gScanDone && gScanEvent != WMI_SCAN_EVENT_COMPLETED) {
		snprintf(res, len, "STEP 4 FAIL: scan %s (reason %u) after %u ms", scan_event_name(gScanEvent), gScanReason, took);
		return false;
	}
	if (gNumBss == 0) {
		snprintf(res, len, "STEP 4 FAIL: scan %s after %u ms but no beacons (WMI %u frames, rx ring %u frames, %u HTT rx "
		    "indications; noise floor %d..%d dBm, receiving on %u of %u channels)", gScanDone ? "completed" : "unfinished",
		    took, gScanFrames, gRingFrames, gHttRxInd, gChanInfoLines ? gNfMin : 0, gChanInfoLines ? gNfMax : 0, gChanHeard,
		    gChanInfoLines);
		return false;
	}
	const struct bss *top = &gBss[0];
	snprintf(res, len, "STEP 4 PASS: listen-only scan found %u networks in %u ms (%u beacons, %u channels); strongest: "
	    "%s, ch %u, %d dBm, %s (beacons: %u over WMI, %u from the rx ring)", gNumBss, took, gScanFrames - gScanDropped +
	    gRingBeacons, gScanForeign,
	    top->ssid_len ? top->ssid : "(hidden)", top->chan, top->dbm, top->sec, gScanFrames - gScanDropped, gRingBeacons);
	return true;
}

