/* Register dumps for the log: RTC_SOC (clock / reset / watchdog / sleep timers) and SOC_CORE. Reads only. */
static void
dump_block(const char *tag, const char *name, uint32_t base, uint32_t count)
{
	for (uint32_t i = 0; i < count; i += 8u) {
		uint32_t o = base + i * 4u;
		A_LOG("%s: %s %05x: %08x %08x %08x %08x %08x %08x %08x %08x", tag, name, o, brd(o), brd(o + 4u), brd(o + 8u),
		    brd(o + 12u), brd(o + 16u), brd(o + 20u), brd(o + 24u), brd(o + 28u));
	}
}

static void
dump_chip(const char *tag)
{
	dump_block(tag, "rtc_soc", 0x800u, 64u);
	dump_block(tag, "soc_core", 0x3a000u, 16u);
}

/*
 * ath10k_pci_wait_for_target_init in interrupt-line mode (qcacld-2.0's "FW sync" does the same): poll
 * FW_INDICATOR every 10 ms, rewriting PCIE_INTR_ENABLE each time ("fix potential race by repeating CORE_BASE
 * writes"), then ath10k_pci_disable_and_clear_intx_irq. The chip's interrupt-disable bit keeps any
 * interrupt from leaving the chip. Logs each change of the indicator.
 */
static uint32_t
wait_rom(const char *tag, uint32_t max_ms, uint32_t *fwi_out)
{
	uint32_t fwi = 0xDEADBEEFu, t = 0;
	for (;;) {
		(void)q_wake();
		uint32_t v = brd(Q_FW_INDICATOR);
		if (v != fwi) {
			A_LOG("%s: fw indicator %08x at %u ms (%u ms after WLAN_EN), intr_cause %08x", tag, v, t,
			    ms_since_power_on(), brd(Q_PCIE_INTR_CAUSE));
			fwi = v;
		}
		if ((v != 0xFFFFFFFFu && (v & (Q_FW_IND_INITIALIZED | Q_FW_IND_EVENT_PENDING))) || t >= max_ms) {
			break;
		}
		bwr(Q_PCIE_INTR_ENABLE, Q_INTR_FW_AND_CE);
		(void)brd(Q_PCIE_INTR_ENABLE);   /* flush the posted write (ath10k) */
		IOSleep(10);
		t += 10;
	}
	uint32_t cause = brd(Q_PCIE_INTR_CAUSE);
	bwr(Q_PCIE_INTR_ENABLE, 0u);                 /* INTR_CLR only works once ENABLE is 0 (ath10k) */
	bwr(Q_PCIE_INTR_CLR, Q_INTR_FW_AND_CE);
	(void)brd(Q_PCIE_INTR_ENABLE);
	A_LOG("%s: boot ROM %s after %u ms (intr_cause %08x before clearing)", tag,
	    (fwi != 0xFFFFFFFFu && (fwi & Q_FW_IND_INITIALIZED)) ? "initialized" : "NOT initialized", t, cause);
	*fwi_out = fwi;
	return t;
}

/* Copy engines, host side (pci_host_ce_config_wlan; fewer CE1 entries: one BMI response at a time). */
static void
init_rings(bool first)
{
	gCe0.base = Q_CE(0);
	gCe1.base = Q_CE(1);
	gCe7.base = Q_CE(7);
	ce_quiet(&gCe0);
	ce_quiet(&gCe1);
	ce_quiet(&gCe7);
	ce_init_src(&gCe0, OFF_CE0_SRC, 16u, BMI_REQ_MAX, first);
	ce_init_dst(&gCe1, OFF_CE1_DST, 16u, first);
	ce_init_src(&gCe7, OFF_CE7_SRC, 2u, DIAG_MAX, first);
	ce_init_dst(&gCe7, OFF_CE7_DST, 2u, first);
	ce_dump("CE0", &gCe0);
	ce_dump("CE1", &gCe1);
	ce_dump("CE7", &gCe7);
}

/* The copy engines treat one 2 MB window as the chip's own memory (CORE_CTRL bits 10:0 << 21); the DMA block
 * must lie outside it. Checked again after a reset. */
static bool
clear_of_window(uint64_t phys, uint64_t size)
{
	uint64_t win = (uint64_t)((brd(Q_CORE_CTRL) & 0x7ffu) << 21);
	return phys >= win + 0x200000u || phys + size <= win;
}

static bool
dma_clear_of_window(char *res, size_t len)
{
	uint32_t win = (brd(Q_CORE_CTRL) & 0x7ffu) << 21;
	if (!clear_of_window(gDmaPhys, DMA_SIZE)) {
		snprintf(res, len, "STEP 2b FAIL: DMA block %08x lies in the chip's own 2 MB window at %08x", gDmaPhys, win);
		return false;
	}
	return true;
}

/* Memory + bus master on both ends; on the chip also "interrupt disable" (no INTx message leaves it). */
static void
command_on(void)
{
	wr32(gDbi, 0x04, (rd32(gDbi, 0x04) & 0xFFFFu) | 0x6u);
	wr32(gConf, 0x04, (rd32(gConf, 0x04) & 0xFFFFu) | 0x406u);
	A_LOG("bus mastering on: rp command %08x, chip command %08x (interrupt disable set)", rd32(gDbi, 0x04),
	    rd32(gConf, 0x04));
}

/*
 * One attempt: diag read of hi_interconnect_state, ath10k_pci_init_config (verified by read-back),
 * ath10k_pci_wake_target_cpu, BMI_GET_TARGET_INFO. *bmi_silent = everything worked except that BMI never answered.
 */
static bool
attempt(const char *how, char *res, size_t len, bool *bmi_silent)
{
	*bmi_silent = false;
	uint32_t pcie_state = 0;
	if (!diag_read32(HI_INTERCONNECT_STATE, &pcie_state)) {
		ce_dump("CE7", &gCe7);
		snprintf(res, len, "STEP 2b FAIL (%s): diag read of hi_interconnect_state (CE7 DMA) timed out", how);
		return false;
	}
	A_LOG("%s: diag read hi_interconnect_state (target %08x = ce %08x): pcie_state at %08x", how, HI_INTERCONNECT_STATE,
	    targ_to_ce(HI_INTERCONNECT_STATE), pcie_state);
	if (pcie_state == 0 || pcie_state == 0xFFFFFFFFu) {
		snprintf(res, len, "STEP 2b FAIL (%s): DMA works but hi_interconnect_state is %08x", how, pcie_state);
		return false;
	}

	uint32_t pipe_cfg = 0, svc_map = 0, cfg_flags = 0, ealloc = 0, flag2 = 0;
	bool ok = diag_read32(pcie_state + PCIE_STATE_PIPE_CFG, &pipe_cfg) &&
	    diag_read32(pcie_state + PCIE_STATE_SVC_MAP, &svc_map) &&
	    diag_read32(pcie_state + PCIE_STATE_CONFIG_FLAGS, &cfg_flags) &&
	    diag_read32(HI_EARLY_ALLOC, &ealloc) &&
	    diag_read32(HI_OPTION_FLAG2, &flag2);
	A_LOG("%s: pipe_cfg %08x svc_map %08x config_flags %08x; hi_early_alloc %08x hi_option_flag2 %08x", how,
	    pipe_cfg, svc_map, cfg_flags, ealloc, flag2);
	if (!ok || pipe_cfg == 0 || svc_map == 0) {
		snprintf(res, len, "STEP 2b FAIL (%s): target config pointers (pipe_cfg %08x svc_map %08x)%s", how, pipe_cfg,
		    svc_map, ok ? "" : ", a diag read timed out");
		return false;
	}
	ok = diag_write(pipe_cfg, kTargetCeConfig, sizeof(kTargetCeConfig)) &&
	    diag_write(svc_map, kServiceMap, sizeof(kServiceMap)) &&
	    diag_write32(pcie_state + PCIE_STATE_CONFIG_FLAGS, cfg_flags & ~PCIE_CONFIG_FLAG_ENABLE_L1) &&
	    diag_write32(HI_EARLY_ALLOC, ealloc | (HI_EARLY_ALLOC_MAGIC << 16) | (HW3_IRAM_BANKS & 0xFu)) &&
	    diag_write32(HI_OPTION_FLAG2, flag2 | HI_OPTION_EARLY_CFG_DONE);
	uint32_t back[6] = { 0, 0, 0, 0, 0, 0 }, flag2_back = 0;
	bool verified = ok && diag_read(pipe_cfg, back, sizeof(back)) && diag_read32(HI_OPTION_FLAG2, &flag2_back) &&
	    memcmp(back, kTargetCeConfig[0], sizeof(back)) == 0 && (flag2_back & HI_OPTION_EARLY_CFG_DONE);
	A_LOG("%s: target config written: %s (pipe 0 reads back %u/%u/%u/%u, hi_option_flag2 %08x)", how,
	    verified ? "verified" : "NOT verified", back[0], back[1], back[2], back[3], flag2_back);
	if (!verified) {
		snprintf(res, len, "STEP 2b FAIL (%s): target config %s", how, ok ? "did not read back" : "diag write timed out");
		return false;
	}
	bwr(Q_CORE_CTRL, brd(Q_CORE_CTRL) | Q_CORE_CTRL_CPU_INTR);

	/* BMI_GET_TARGET_INFO (ath10k_bmi_get_target_info): 4-byte command, response { len, version, type }. */
	uint32_t cmd = BMI_GET_TARGET_INFO, rsp[3] = { 0, 0, 0 }, rlen = sizeof(rsp);
	if (!bmi_exchange(&cmd, sizeof(cmd), rsp, &rlen)) {
		ce_dump("CE0", &gCe0);
		ce_dump("CE1", &gCe1);
		*bmi_silent = true;
		snprintf(res, len, "STEP 2b FAIL (%s): no answer to BMI_GET_TARGET_INFO in 3 s (fw indicator %08x); DMA, diag "
		    "and target config OK", how, brd(Q_FW_INDICATOR));
		return false;
	}
	A_LOG("%s: BMI_GET_TARGET_INFO: %u bytes: len %u version %08x type %u", how, rlen, rsp[0], rsp[1], rsp[2]);
	if (rlen < sizeof(rsp)) {
		snprintf(res, len, "STEP 2b FAIL (%s): BMI_GET_TARGET_INFO answered %u bytes, expected 12", how, rlen);
		return false;
	}
	snprintf(res, len, "%s (%s): BMI target version %08x type %u (hw3.2 = %08x); DMA, diag window, target config OK",
	    rsp[1] == QCA6174_HW_3_2_VERSION ? "STEP 2b PASS" : "STEP 2b: unexpected target version", how, rsp[1], rsp[2],
	    QCA6174_HW_3_2_VERSION);
	return rsp[1] == QCA6174_HW_3_2_VERSION;
}

/* ---------------------------------------------------------------------------------------------------- */
/* step 2c: BMI commands (bmi.c), the firmware file (core.c), segment download (hw.c), HTC ready (htc.c) */

static bool
bmi_read32(uint32_t addr, uint32_t *v)
{
	uint32_t cmd[3] = { BMI_READ_MEMORY, addr, 4u }, len = 4u;
	*v = 0;
	return bmi_cmd(cmd, sizeof(cmd), v, &len) && len == 4u;
}

/* ath10k_bmi_write_memory: chunks of BMI_MAX_DATA_SIZE minus the 12-byte header, each rounded up to 4 bytes */
static bool
bmi_write_mem(uint32_t addr, const void *data, uint32_t len)
{
	const uint8_t *src = (const uint8_t *)data;
	uint32_t cmd[BMI_MAX_DATA_SIZE / 4u];
	while (len > 0) {
		uint32_t n = len < BMI_MAX_DATA_SIZE - 12u ? len : BMI_MAX_DATA_SIZE - 12u;
		uint32_t padded = (n + 3u) & ~3u;
		bzero(cmd, sizeof(cmd));
		cmd[0] = BMI_WRITE_MEMORY;
		cmd[1] = addr;
		cmd[2] = padded;
		memcpy(&cmd[3], src, n);
		if (!bmi_cmd(cmd, 12u + padded, NULL, NULL)) {
			A_LOG("BMI write of %u bytes at %08x failed", n, addr);
			return false;
		}
		addr += n;
		src += n;
		len -= n;
	}
	return true;
}

static bool
bmi_write32(uint32_t addr, uint32_t v)
{
	return bmi_write_mem(addr, &v, 4u);
}

static bool
bmi_execute(uint32_t addr, uint32_t param, uint32_t *result)
{
	uint32_t cmd[3] = { BMI_EXECUTE, addr, param }, len = 4u;
	*result = 0xDEADBEEFu;
	return bmi_cmd(cmd, sizeof(cmd), result, &len) && len == 4u;
}

static bool
bmi_simple(uint32_t id, uint32_t arg)   /* BMI_LZ_STREAM_START, BMI_SET_APP_START: no response */
{
	uint32_t cmd[2] = { id, arg };
	return bmi_cmd(cmd, sizeof(cmd), NULL, NULL);
}

/* ath10k_bmi_read_soc_reg / _write_soc_reg */
static bool
bmi_read_soc(uint32_t addr, uint32_t *v)
{
	uint32_t cmd[2] = { BMI_READ_SOC_REGISTER, addr }, len = 4u;
	*v = 0;
	return bmi_cmd(cmd, sizeof(cmd), v, &len) && len == 4u;
}

static bool
bmi_write_soc(uint32_t addr, uint32_t v)
{
	uint32_t cmd[3] = { BMI_WRITE_SOC_REGISTER, addr, v };
	return bmi_cmd(cmd, sizeof(cmd), NULL, NULL);
}

/* Read-modify-write of one SoC register over BMI, read back afterwards (qcacld's "a"/"b" steps). */
static bool
bmi_rmw_soc(uint32_t addr, uint32_t clear, uint32_t set, uint32_t *before, uint32_t *after)
{
	return bmi_read_soc(addr, before) && bmi_write_soc(addr, (*before & ~clear) | set) && bmi_read_soc(addr, after);
}

/* RTC_SYNC_STATUS until PLL_CHANGING clears: the number of polls, or -1 (BMI failed, or 10000 polls) */
static int
pll_wait(void)
{
	for (int i = 0; i < 10000; i++) {
		uint32_t v = 0;
		if (!bmi_read_soc(RTC_WMAC_BASE | RTC_SYNC_STATUS_OFFSET, &v)) {
			return -1;
		}
		if ((v & 0x20u) == 0) {
			return i;
		}
		IODelay(10);
	}
	return -1;
}

/* WLAN PLL settings per crystal (qcacld ol_fw_populate_clk_settings; ath10k's qca6174_clk is the same except for
 * 40 MHz, where 0x11 is the one that gives the same 704 MHz as every other row) */
static const struct {
	uint32_t hz, div, rnfrac, settle;
} kRefClk[8] = {
	{ 48000000u, 0x0Eu, 0x2AAA8u, 2400u }, { 19200000u, 0x24u, 0x2AAA8u, 960u }, { 24000000u, 0x1Du, 0x15551u, 1200u },
	{ 26000000u, 0x1Bu, 0x04EC4u, 1300u }, { 37400000u, 0x12u, 0x34B49u, 1870u }, { 38400000u, 0x12u, 0x15551u, 1920u },
	{ 40000000u, 0x11u, 0x26665u, 2000u }, { 52000000u, 0x1Bu, 0x04EC4u, 2600u },
};

/*
 * qcacld ol_patch_pll_switch (= ath10k_hw_qca6174_enable_pll_clock): the baseband and WLAN PLLs set up for the
 * board's crystal (from the efuse), the CPU moved onto the PLL, and the firmware told (cpu_pll_init_done, its
 * CPU speed). Both host drivers do this before every firmware download; qcacld, the phone's own driver, does
 * not download at all if it fails. Returns NULL when done, else the step that failed.
 */
static const char *
pll_switch(void)
{
	uint32_t efuse = 0, bb0 = 0, bb1 = 0, st0 = 0, st1 = 0, cc0 = 0, cc1 = 0, pc0 = 0, pc1 = 0, by1 = 0, cpu0 = 0, cpu1 = 0;
	uint32_t nopwd = 0, tmp = 0;
	if (!bmi_read_soc(RTC_SOC_BASE | EFUSE_OFFSET, &efuse)) {
		return "efuse read";
	}
	uint32_t sel = (efuse >> 8) & 7u;
	A_LOG("PLL: efuse %08x: crystal %u Hz (xtal_sel %u)", efuse, kRefClk[sel].hz, sel);
	if (!bmi_rmw_soc(RTC_SOC_BASE | BB_PLL_CONFIG_OFFSET, 0x001FFFFFu, (kRefClk[sel].rnfrac & 0x3FFFFu) | (1u << 18),
	    &bb0, &bb1)) {
		return "bb_pll_config";
	}
	if (!bmi_rmw_soc(RTC_WMAC_BASE | WLAN_PLL_SETTLE_OFFSET, 0x7FFu, kRefClk[sel].settle & 0x7FFu, &st0, &st1)) {
		return "wlan_pll_settle";
	}
	if (!bmi_rmw_soc(RTC_SOC_BASE | SOC_CORE_CLK_CTRL_OFFSET, 0x7u, 1u, &cc0, &cc1)) {
		return "core_clk_ctrl";
	}
	if (!bmi_write32(CORE_CLK_DIV_ADDR, 1u)) {
		return "core_clk_div";
	}
	/* refdiv 0, div, NOPWD set: the PLL powers up but stays bypassed */
	if (!bmi_rmw_soc(RTC_WMAC_BASE | WLAN_PLL_CONTROL_OFFSET, 0x3FFu | 0x3C00u | (1u << 18),
	    (kRefClk[sel].div & 0x3FFu) | (1u << 18), &pc0, &pc1)) {
		return "wlan_pll_control";
	}
	IODelay(100);
	int lock1 = pll_wait();
	if (lock1 < 0) {
		return "pll lock (power up)";
	}
	if (!bmi_rmw_soc(RTC_WMAC_BASE | WLAN_PLL_CONTROL_OFFSET, 1u << 16, 0u, &tmp, &by1)) {
		return "pll bypass off";
	}
	int lock2 = pll_wait();
	if (lock2 < 0) {
		return "pll lock (bypass off)";
	}
	if (!bmi_rmw_soc(RTC_SOC_BASE | SOC_CPU_CLOCK_OFFSET, 0x3u, 1u, &cpu0, &cpu1)) {
		return "cpu_clock";
	}
	if (!bmi_rmw_soc(RTC_WMAC_BASE | WLAN_PLL_CONTROL_OFFSET, 1u << 18, 0u, &tmp, &nopwd)) {
		return "pll nopwd off";
	}
	if (!bmi_write32(CPU_PLL_INIT_DONE_ADDR, 1u) || !bmi_write32(CPU_SPEED_ADDR, TARGET_CPU_FREQ)) {
		return "pll_init_done / cpu speed";
	}
	A_LOG("PLL: bb_pll_config %08x->%08x, settle %08x->%08x, core_clk_ctrl %08x->%08x, wlan_pll_control %08x->%08x",
	    bb0, bb1, st0, st1, cc0, cc1, pc0, pc1);
	A_LOG("PLL: locked after %d + %d polls, control %08x then %08x, cpu_clock %08x->%08x; firmware told %u Hz", lock1, lock2,
	    by1, nopwd, cpu0, cpu1, TARGET_CPU_FREQ);
	return NULL;
}

/* ath10k_bmi_lz_data: len is a multiple of 4; chunks of BMI_MAX_DATA_SIZE minus the 8-byte header */
static bool
bmi_lz_data(const uint8_t *data, uint32_t len)
{
	uint32_t cmd[BMI_MAX_DATA_SIZE / 4u];
	while (len > 0) {
		uint32_t n = len < BMI_MAX_DATA_SIZE - 8u ? len : BMI_MAX_DATA_SIZE - 8u;
		cmd[0] = BMI_LZ_DATA;
		cmd[1] = n;
		memcpy(&cmd[2], data, n);
		if (!bmi_cmd(cmd, 8u + n, NULL, NULL)) {
			return false;
		}
		data += n;
		len -= n;
	}
	return true;
}

/* ath10k_bmi_fast_download: stream start, the data, a zero-padded last word, then a stream start at 0 that
 * "serves mainly to flush Target caches" */
static bool
bmi_fast_download(uint32_t addr, const uint8_t *data, uint32_t len)
{
	uint32_t head = len & ~3u;
	uint8_t trailer[4] = { 0, 0, 0, 0 };
	if (!bmi_simple(BMI_LZ_STREAM_START, addr) || !bmi_lz_data(data, head)) {
		return false;
	}
	if (len > head) {
		memcpy(trailer, data + head, len - head);
		if (!bmi_lz_data(trailer, 4u)) {
			return false;
		}
	}
	return bmi_simple(BMI_LZ_STREAM_START, 0u);
}

/* The firmware-N.bin container (ath10k_core_fetch_firmware_api_n): magic, then { id, len, data } IEs */
struct fw_file {
	const uint8_t *otp, *image;
	uint32_t otp_len, image_len, features, wmi_op, htt_op;
	char version[64];
};

static bool
fw_parse(const uint8_t *fw, uint32_t len, struct fw_file *f)
{
	static const char magic[] = "QCA-ATH10K";   /* 11 bytes with the NUL, padded to 12 */
	bzero(f, sizeof(*f));
	if (len < 12u || memcmp(fw, magic, sizeof(magic)) != 0) {
		return false;
	}
	uint32_t off = 12u;
	while (off + 8u <= len) {
		uint32_t id, ie_len;
		memcpy(&id, fw + off, 4u);
		memcpy(&ie_len, fw + off + 4u, 4u);
		off += 8u;
		if (ie_len > len - off) {
			return false;
		}
		const uint8_t *d = fw + off;
		switch (id) {
		case 0:   /* FW_VERSION */
			memcpy(f->version, d, ie_len < sizeof(f->version) - 1u ? ie_len : sizeof(f->version) - 1u);
			break;
		case 2:   /* FEATURES (bitmap) */
			memcpy(&f->features, d, ie_len < 4u ? ie_len : 4u);
			break;
		case 3:   /* FW_IMAGE */
			f->image = d;
			f->image_len = ie_len;
			break;
		case 4:   /* OTP_IMAGE */
			f->otp = d;
			f->otp_len = ie_len;
			break;
		case 5:   /* WMI_OP_VERSION */
			if (ie_len >= 4u) {
				memcpy(&f->wmi_op, d, 4u);
			}
			break;
		case 6:   /* HTT_OP_VERSION */
			if (ie_len >= 4u) {
				memcpy(&f->htt_op, d, 4u);
			}
			break;
		default:
			break;
		}
		off += (ie_len + 3u) & ~3u;
	}
	return f->image != NULL;
}

/* ath10k_pci_diag_write_mem: DIAG_TRANSFER_LIMIT pieces */
static bool
diag_write_mem(uint32_t taddr, const uint8_t *data, uint32_t len)
{
	while (len > 0) {
		uint32_t n = len < DIAG_MAX ? len : DIAG_MAX;
		if (!diag_write(taddr, data, n)) {
			return false;
		}
		taddr += n;
		data += n;
		len -= n;
	}
	return true;
}

/* ath10k_hw_diag_segment_download: above the first MB of DRAM, point the 1 MB window (CPU_ADDR_MSB) at the
 * segment's region, split a segment that crosses a region boundary, and point the window back at DRAM. */
static bool
segment_download(uint32_t addr, const uint8_t *data, uint32_t len)
{
	if (addr < DRAM_BASE_ADDRESS + REGION_ACCESS_SIZE) {
		return diag_write_mem(addr, data, len);
	}
	uint32_t in_region = addr & (REGION_ACCESS_SIZE - 1u);
	bool ok;
	bwr(Q_FW_RAM_CONFIG, (addr >> 20) & 0xFu);
	if (in_region + len > REGION_ACCESS_SIZE) {
		uint32_t first = REGION_ACCESS_SIZE - in_region;
		ok = diag_write_mem(addr, data, first);
		if (ok) {
			bwr(Q_FW_RAM_CONFIG, ((addr >> 20) & 0xFu) + 1u);
			ok = diag_write_mem(addr & ~(REGION_ACCESS_SIZE - 1u), data + first, len - first);
		}
	} else {
		ok = diag_write_mem(addr, data, len);
	}
	bwr(Q_FW_RAM_CONFIG, (DRAM_BASE_ADDRESS >> 20) & 0xFu);
	return ok;
}

/* ath10k_hw_diag_fast_download: an uncompressed SGMT image, segment by segment */
static bool
diag_fast_download(const uint8_t *img, uint32_t len)
{
	uint32_t magic, flags, nseg = 0, bytes = 0;
	if (len < 8u) {
		return false;
	}
	memcpy(&magic, img, 4u);
	memcpy(&flags, img + 4u, 4u);
	if (magic != SGMT_MAGIC || flags != 0) {
		A_LOG("firmware image: magic %08x flags %08x, not an uncompressed SGMT image", magic, flags);
		return false;
	}
	uint32_t off = 8u;
	while (off + 8u <= len) {
		uint32_t addr, seg_len;
		memcpy(&addr, img + off, 4u);
		memcpy(&seg_len, img + off + 4u, 4u);
		off += 8u;
		if (seg_len == SGMT_DONE) {
			A_LOG("firmware image: %u segments, %u bytes through the diagnostic window", nseg, bytes);
			return true;
		}
		if (seg_len == SGMT_BEGINADDR) {
			A_LOG("firmware image: start address %08x", addr);
			if (!bmi_simple(BMI_SET_APP_START, addr)) {
				return false;
			}
			continue;
		}
		if (seg_len == SGMT_BDDATA || seg_len == SGMT_EXEC || seg_len > len - off) {
			A_LOG("firmware image: unsupported or truncated segment (%08x bytes at %08x)", seg_len, addr);
			return false;
		}
		if (!segment_download(addr, img + off, seg_len)) {
			A_LOG("firmware image: segment of %u bytes at %08x failed", seg_len, addr);
			return false;
		}
		nseg++;
		bytes += seg_len;
		off += seg_len;
	}
	A_LOG("%s", "firmware image: no end marker");
	return false;
}

/* ath10k_pci_dump_registers: the firmware's crash record, REG_DUMP_COUNT words at hi_failure_state */
static void
dump_fw_crash(void)
{
	uint32_t at = 0, regs[REG_DUMP_COUNT];
	if (!diag_read32(HI_FAILURE_STATE, &at) || at == 0 || !diag_read(at, regs, sizeof(regs))) {
		A_LOG("firmware crash record: unreadable (hi_failure_state %08x)", at);
		return;
	}
	for (uint32_t i = 0; i < REG_DUMP_COUNT; i += 6u) {
		A_LOG("firmware crash record %02u: %08x %08x %08x %08x %08x %08x", i, regs[i], regs[i + 1u], regs[i + 2u],
		    regs[i + 3u], regs[i + 4u], regs[i + 5u]);
	}
}

/* ath10k_htc_wait_target: receive buffers on CE1 (ath10k_pci_hif_start posts them), then the control message
 * HTC_MSG_READY_ID { credit_count, credit_size, max_endpoints[, htc_version, max_msgs_per_htc_bundle] } */
static bool
htc_wait_ready(const char *fw_version, char *res, size_t len)
{
	for (uint32_t i = 0; i < HTC_RX_COUNT; i++) {
		if (!ce_post_rx(&gCe1, gDmaPhys + OFF_HTC_RX + i * HTC_RX_SIZE)) {
			snprintf(res, len, "STEP 2c FAIL: could not post receive buffer %u on CE1", i);
			return false;
		}
	}
	for (uint32_t t = 0; t <= 3000u; t++) {
		uint32_t n = 0, at = 0;
		if (ce_recv_done(&gCe1, &n, &at)) {
			const uint8_t *m = gDma + (at - gDmaPhys);
			uint16_t mlen, id, credits, csize;
			if (at < gDmaPhys + OFF_HTC_RX || at >= gDmaPhys + OFF_HTC_RX + HTC_RX_COUNT * HTC_RX_SIZE || n < 8u + 8u) {
				snprintf(res, len, "STEP 2c FAIL: odd first message from the firmware (%u bytes at %08x)", n, at);
				return false;
			}
			memcpy(&mlen, m + 2, 2u);
			memcpy(&id, m + 8, 2u);
			memcpy(&credits, m + 10, 2u);
			memcpy(&csize, m + 12, 2u);
			A_LOG("first message after %u ms: %u bytes, endpoint %u flags %02x len %u: %02x %02x %02x %02x %02x %02x %02x %02x "
			    "%02x %02x %02x %02x", t, n, m[0], m[1], mlen, m[8], m[9], m[10], m[11], m[12], m[13], m[14], m[15],
			    m[16], m[17], m[18], m[19]);
			if (m[0] != 0 || id != HTC_MSG_READY_ID || credits == 0 || csize == 0) {
				snprintf(res, len, "STEP 2c FAIL: firmware sent message %u on endpoint %u (credits %u x %u), not HTC ready",
				    id, m[0], credits, csize);
				return false;
			}
			snprintf(res, len, "STEP 2c PASS: firmware %s booted: HTC ready, %u credits of %u bytes, %u endpoints%s",
			    fw_version, credits, csize, m[14], mlen >= 10u ? ", extended" : "");
			gHtcCredits = credits;
			gHtcCreditSize = csize;
			(void)ce_post_rx(&gCe1, at);   /* the buffer goes back on the ring for step 3 */
			return true;
		}
		if (t % 10u == 0) {
			uint32_t fwi = brd(Q_FW_INDICATOR);
			if (fwi != 0xFFFFFFFFu && (fwi & Q_FW_IND_EVENT_PENDING)) {
				A_LOG("firmware crashed %u ms after BMI_DONE (fw indicator %08x)", t, fwi);
				dump_fw_crash();
				snprintf(res, len, "STEP 2c FAIL: firmware crashed %u ms after BMI_DONE (fw indicator %08x)", t, fwi);
				return false;
			}
		}
		IOSleep(1);
	}
	ce_dump("CE1", &gCe1);
	snprintf(res, len, "STEP 2c FAIL: no HTC ready from the firmware in 3 s (fw indicator %08x)", brd(Q_FW_INDICATOR));
	return false;
}

/* ath10k_core_start, BMI part: configure target, board data + OTP, firmware, UART off, BMI_DONE, HTC ready */
static bool
run2c(char *res, size_t len)
{
	struct fw_file f;
	gStep = "2c";
	if (kOp2WifiFwLen == 0 || kOp2WifiBoardLen == 0) {
		snprintf(res, len, "%s", "STEP 2c SKIPPED: no firmware built in (firmware/qca6174/ with firmware-6.bin and "
		    "bdwlan30.bin, then rebuild)");
		return false;
	}
	if (!fw_parse(kOp2WifiFw, kOp2WifiFwLen, &f)) {
		snprintf(res, len, "STEP 2c FAIL: firmware-6.bin (%u bytes) is not an ath10k firmware container", kOp2WifiFwLen);
		return false;
	}
	A_LOG("firmware %s: otp %u bytes, image %u bytes, features %08x, wmi op %u, htt op %u; board data %u bytes",
	    f.version, f.otp_len, f.image_len, f.features, f.wmi_op, f.htt_op, kOp2WifiBoardLen);

	/* ath10k_init_configure_target */
	uint32_t opt = 0;
	bool ok = bmi_write32(HI_APP_HOST_INTEREST, HTC_PROTOCOL_VERSION) && bmi_read32(HI_OPTION_FLAG, &opt) &&
	    /* 1 device, AP mode, MAC method 1; and the firmware's debug log on (qcacld with gEnablefwlog) */
	    bmi_write32(HI_OPTION_FLAG, (opt | (1u << 9) | (2u << 12) | (1u << 3)) & ~HI_OPTION_DISABLE_DBGLOG) &&
	    bmi_write32(HI_BE, 0u) && bmi_write32(HI_FW_SWAP, 0u) &&
	    bmi_write32(HI_HCI_UART_PWR_MGMT_EXT, QCA6174_DEVICE_ID);
	if (!ok) {
		snprintf(res, len, "%s", "STEP 2c FAIL: configuring the target over BMI failed");
		return false;
	}

	/* the PLL switch both host drivers make before downloading anything; a failure is logged, not fatal (ath10k) */
	const char *pll = pll_switch();
	if (pll != NULL) {
		A_LOG("PLL: FAILED at %s; going on with the reference clock", pll);
	}

	/* qcacld ol_download_firmware, and ath10k on its first boot (ath10k_core_get_board_id_from_otp): the OTP image
	 * run once with BMI_PARAM_GET_EEPROM_BOARD_ID before the board data goes in */
	if (f.otp_len > 0) {
		uint32_t r = 0;
		ok = bmi_fast_download(BMI_PATCH_LOAD_ADDR, f.otp, f.otp_len) &&
		    bmi_execute(BMI_PATCH_LOAD_ADDR, BMI_PARAM_GET_EEPROM_BOARD_ID, &r);
		A_LOG("otp board id: %s, result %08x (status %u, board id %u, chip id %u, extended board id %s)",
		    ok ? "ran" : "FAILED", r, r & 0xFFu, (r & 0x7C00u) >> 10, (r & 0x18000u) >> 15, (r & 0x40000u) ? "yes" : "no");
		if (!ok) {
			snprintf(res, len, "%s", "STEP 2c FAIL: OTP board ID run over BMI");
			return false;
		}
	}

	/* ath10k_download_board_data (QCA6174 has no extended board data) */
	uint32_t ext = 0, board = 0;
	ok = bmi_read32(HI_BOARD_EXT_DATA, &ext) && bmi_read32(HI_BOARD_DATA, &board) && board != 0 &&
	    bmi_write_mem(board, kOp2WifiBoard, kOp2WifiBoardLen < QCA6174_BOARD_DATA_SZ ? kOp2WifiBoardLen :
	    QCA6174_BOARD_DATA_SZ) && bmi_write32(HI_BOARD_DATA_INITIALIZED, 1u);
	A_LOG("board data: %u bytes to %08x%s (hi_option_flag was %08x, board ext data address %08x)", kOp2WifiBoardLen,
	    board, ok ? "" : " FAILED", opt, ext);
	if (!ok) {
		snprintf(res, len, "STEP 2c FAIL: board data download (hi_board_data %08x)", board);
		return false;
	}

	/* ath10k_download_and_run_otp: the result is ignored (firmware feature IGNORE_OTP_RESULT) */
	if (f.otp_len > 0) {
		uint32_t result = 0;
		ok = bmi_fast_download(BMI_PATCH_LOAD_ADDR, f.otp, f.otp_len) && bmi_execute(BMI_PATCH_LOAD_ADDR, 0u, &result);
		A_LOG("otp: %u bytes over BMI, executed: %s, result %u", f.otp_len, ok ? "yes" : "FAILED", result);
		if (!ok) {
			snprintf(res, len, "%s", "STEP 2c FAIL: OTP download or execution over BMI");
			return false;
		}
	}

	/* ath10k_download_fw: the diagnostic window (fw_diag_ce_download), BMI as the fallback */
	if (!diag_fast_download(f.image, f.image_len)) {
		A_LOG("%s", "firmware through the diagnostic window failed; BMI LZ stream instead");
		if (!bmi_fast_download(BMI_PATCH_LOAD_ADDR, f.image, f.image_len)) {
			snprintf(res, len, "%s", "STEP 2c FAIL: firmware download (diagnostic window and BMI)");
			return false;
		}
	}

	/* ath10k_init_uart, then BMI_DONE: the firmware starts */
	uint32_t done = BMI_DONE;
	if (!bmi_write32(HI_SERIAL_ENABLE, 0u) || !bmi_cmd(&done, sizeof(done), NULL, NULL)) {
		snprintf(res, len, "%s", "STEP 2c FAIL: BMI_DONE was not accepted");
		return false;
	}
	A_LOG("%s", "BMI_DONE sent; waiting for the firmware's HTC ready");
	return htc_wait_ready(f.version, res, len);
}

