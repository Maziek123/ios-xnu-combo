/* BMI (pci.c ath10k_pci_hif_exchange_bmi_msg): request on CE0, response on CE1, 3 s                    */

/* resp == NULL: a command without a response (BMI_WRITE_MEMORY, LZ, SET_APP_START, DONE): wait for the send only. */
static bool
bmi_cmd(const void *req, uint32_t req_len, void *resp, uint32_t *resp_len)
{
	uint8_t *rq = gDma + OFF_BMI_REQ, *rs = gDma + OFF_BMI_RESP;
	uint32_t got = 0;
	memcpy(rq, req, req_len);
	if (resp != NULL) {
		if (gCe1.dst.write_index != gCe1.dst.sw_index) {
			A_LOG("%s", "BMI: a response buffer is still posted on CE1 (same address); reusing it");
		} else if (!ce_post_rx(&gCe1, gDmaPhys + OFF_BMI_RESP)) {
			A_LOG("%s", "BMI: CE1 ring full");
			return false;
		}
	}
	if (!ce_send(&gCe0, gDmaPhys + OFF_BMI_REQ, req_len, BMI_SEND_FLAGS)) {
		A_LOG("%s", "BMI: ring full");
		return false;
	}
	if (!ce_wait(&gCe0, resp != NULL ? &gCe1 : NULL, &got, 3000000u, "BMI exchange")) {
		return false;
	}
	if (resp == NULL) {
		return true;
	}
	if (got > BMI_RESP_MAX) {
		A_LOG("BMI: %u-byte response overran the %u-byte buffer (inside the DMA block)", got, BMI_RESP_MAX);
		got = BMI_RESP_MAX;
	}
	*resp_len = got < *resp_len ? got : *resp_len;
	memcpy(resp, rs, *resp_len);
	return true;
}

static bool
bmi_exchange(const void *req, uint32_t req_len, void *resp, uint32_t *resp_len)
{
	return bmi_cmd(req, req_len, resp, resp_len);
}

