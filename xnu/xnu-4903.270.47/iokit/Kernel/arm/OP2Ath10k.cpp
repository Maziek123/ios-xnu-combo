static bool
run5(char *res, size_t len)
{
	gStep = "5";
	gDrainHook = pump;
	gMgmtHook = join_mgmt;
	gDataHook = join_data;
	uint32_t t0 = ms_since_power_on();
	char name[33];
	ssid_print(name, sizeof(name));
	if (kOp2WifiSsidLen == 0) {
		snprintf(res, len, "%s", "STEP 5 FAIL: no network configured (firmware/qca6174/wifi-network.txt: name on the "
		    "first line, password on the second; see the README), rebuild");
		return false;
	}
	/* Not in the listen-only scan: ask for it by name on 2.4 GHz (an access point answers a probe request with a
	 * probe response to us, retried until we acknowledge it: more chances than a passing beacon), up to 4 times;
	 * then one more listen-only scan of every channel (a hotspot on 5 GHz). */
	struct bss *b = find_target();
	uint32_t round = 1, directed = 0;
	gProbeSsid = kOp2WifiSsid;
	gProbeSsidLen = kOp2WifiSsidLen;
	if (b == NULL) {
		A_LOG("%s not heard in the scan (%u networks); asking for it by name on 2.4 GHz channels 1-11", name, gNumBss);
		if (!scan_chan_list(true)) {
			return join_fail(res, len, "the channel list for probing could not be sent");
		}
	}
	for (; b == NULL && directed < 4u; directed++, round++) {
		uint32_t t1 = ms_since_power_on();
		const char *why = rescan(round, true, res, len);
		if (why != NULL) {
			return gFwDown ? false : join_fail(res, len, why);
		}
		b = find_target();
		A_LOG("probe round %u: %s after %u ms (%u networks known)", directed + 1u, b != NULL ? "found" : "not heard",
		    ms_since_power_on() - t1, gNumBss);
	}
	if (b == NULL) {
		A_LOG("%s", "one more listen-only scan of every channel (2.4 and 5 GHz)");
		const char *why = rescan(round, false, res, len);
		if (why != NULL) {
			return gFwDown ? false : join_fail(res, len, why);
		}
		b = find_target();
	}
	if (b == NULL) {
		return join_fail(res, len, "not heard in 2 listen-only scans, and no answer to probe requests on 2.4 GHz "
		    "(4 rounds); is the Personal Hotspot screen open on the iPhone?");
	}
	gAp = *b;
	memcpy(gBssid, gAp.bssid, 6u);
	gJoinOpen = gAp.rsn_len == 0 && (gAp.cap & 0x0010u) == 0;
	A_LOG("network %s: BSSID %02x:%02x:%02x:%02x:%02x:%02x, channel %u (%u MHz), %d dBm, beacon interval %u, "
	    "capabilities %04x, %s%s%s; heard %u time(s)%s", name, gBssid[0], gBssid[1], gBssid[2], gBssid[3], gBssid[4],
	    gBssid[5], gAp.chan, gAp.mhz, gAp.dbm, gAp.bintval, gAp.cap, gJoinOpen ? "open" : gAp.rsn_len ? "RSN" :
	    "WEP/WPA", gAp.ht ? ", HT" : "", gAp.wmm ? ", WMM" : "", gAp.frames, gAp.probed ?
	    ", answered our probe requests" : "");
	if (!gJoinOpen) {
		if (gAp.rsn_len == 0) {
			return join_fail(res, len, "it uses WEP or WPA1, which are not supported here");
		}
		const char *bad = rsn_check(&gAp);
		if (bad != NULL) {
			return join_fail(res, len, bad);
		}
		if (kOp2WifiOpen) {
			return join_fail(res, len, "it needs a password, but none is configured");
		}
	}

	/* ath10k: power save off, vdev start on the channel (vdev start response), peer for the access point (HTT
	 * peer map) */
	if (!sta_ps_off() || !vdev_start()) {
		return join_fail(res, len, "the vdev start command could not be sent");
	}
	if (!wait_for([]() { return gVdevStartResp; }, 3000u, "the vdev start response", res, len)) {
		return gFwDown ? false : join_fail(res, len, "no vdev start response within 3 s");
	}
	gVdevStarted = true;
	if (gVdevStartStatus != 0) {
		char why[64];
		snprintf(why, sizeof(why), "the firmware refused to start on %u MHz (status %u)", gAp.mhz, gVdevStartStatus);
		return join_fail(res, len, why);
	}
	if (!peer_cmd(WMI_TLV_PEER_CREATE_CMDID, WMI_TLV_TAG_PEER_CREATE_CMD, true)) {
		return join_fail(res, len, "the peer create command could not be sent");
	}
	gPeerCreated = true;
	if (!wait_for([]() { return gPeerMapped; }, 3000u, "the peer map", res, len)) {
		return gFwDown ? false : join_fail(res, len, "the firmware did not map the access point's peer within 3 s");
	}
	A_LOG("on channel %u, peer %u for the access point", gAp.chan, gPeerId);

	/* open system authentication, then association; three tries each, 500 ms apart */
	uint8_t f[256];
	uint32_t st = 0, auth_tries = 0, assoc_tries = 0;
	const char *txerr = NULL;
	for (auth_tries = 1; auth_tries <= 3u && !gAuthResp; auth_tries++) {
		uint32_t n = mgmt_hdr(f, 0xB0u);
		bzero(f + n, 6u);
		f[n + 2u] = 1u;   /* algorithm 0 (open), transaction 1, status 0 */
		txerr = htt_tx(f, n + 6u, true, true, &st, res, len);
		if (txerr != NULL) {
			return gFwDown ? false : join_fail(res, len, txerr);
		}
		A_LOG("authentication request %u: %s", auth_tries, tx_status_name(st));
		(void)wait_for([]() { return gAuthResp || gDeauth; }, 500u, "the authentication response", res, len);
		if (gFwDown) {
			return false;
		}
	}
	char why[128];
	if (gDeauth) {
		snprintf(why, sizeof(why), "it sent %s, reason %u (%s)", gDeauthSubtype == 0xC0u ? "a deauthentication" :
		    "a disassociation", gDeauthReason, reason_name(gDeauthReason));
		return join_fail(res, len, why);
	}
	if (!gAuthResp) {
		snprintf(why, sizeof(why), "no authentication response to 3 requests (last one %s)", tx_status_name(st));
		return join_fail(res, len, why);
	}
	if (gAuthStatus != 0) {
		snprintf(why, sizeof(why), "authentication refused, status %u (%s)", gAuthStatus, status_name(gAuthStatus));
		return join_fail(res, len, why);
	}
	for (assoc_tries = 1; assoc_tries <= 3u && !gAssocResp && !gDeauth; assoc_tries++) {
		uint32_t n = build_assoc(f);
		txerr = htt_tx(f, n, true, true, &st, res, len);
		if (txerr != NULL) {
			return gFwDown ? false : join_fail(res, len, txerr);
		}
		A_LOG("association request %u (%u bytes): %s", assoc_tries, n, tx_status_name(st));
		(void)wait_for([]() { return gAssocResp || gDeauth; }, 500u, "the association response", res, len);
		if (gFwDown) {
			return false;
		}
	}
	if (gDeauth) {
		snprintf(why, sizeof(why), "it sent %s, reason %u (%s)", gDeauthSubtype == 0xC0u ? "a deauthentication" :
		    "a disassociation", gDeauthReason, reason_name(gDeauthReason));
		return join_fail(res, len, why);
	}
	if (!gAssocResp) {
		snprintf(why, sizeof(why), "no association response to 3 requests (last one %s)", tx_status_name(st));
		return join_fail(res, len, why);
	}
	if (gAssocStatus != 0) {
		snprintf(why, sizeof(why), "association refused, status %u (%s)", gAssocStatus, status_name(gAssocStatus));
		return join_fail(res, len, why);
	}
	gAssociated = true;

	/* ath10k_bss_assoc: peer assoc, then vdev up with the association id */
	uint32_t nr = 0, mode = 0;
	if (!peer_assoc(&nr, &mode) || !vdev_up()) {
		return join_fail(res, len, "the peer assoc or vdev up command could not be sent");
	}
	gVdevUp = true;
	pump();
	snprintf(res, len, "STEP 5 PASS: associated with %s (BSSID %02x:%02x:%02x:%02x:%02x:%02x, channel %u, %d dBm), "
	    "AID %u, %s, %u rates (%s); %u ms, authentication after %u request(s), association after %u", name, gBssid[0],
	    gBssid[1], gBssid[2], gBssid[3], gBssid[4], gBssid[5], gAp.chan, gAp.dbm, gAid, gJoinOpen ? "open network" :
	    "WPA2-PSK CCMP", nr, mode == WMI_MODE_11A ? "11a" : mode == WMI_MODE_11G ? "11g" : "11b",
	    ms_since_power_on() - t0, auth_tries - 1u, assoc_tries - 1u);
	return true;
}

/* ---- step 6: the 4-way handshake (we are the supplicant), keys into the firmware, port open ---- */

struct ekey {
	const uint8_t *e;     /* the 802.1X frame */
	uint32_t n;           /* its length (header + body) */
	uint32_t ki;          /* key information */
	uint32_t kdlen;
};

static bool
ek_parse(const uint8_t *e, uint32_t n, struct ekey *k)
{
	if (n < EK_HDR || e[1] != 3u || e[4] != 2u) {    /* EAPOL-Key, RSN descriptor */
		return false;
	}
	uint32_t body = be16(e + 2);
	if (4u + body > n || 4u + body < EK_HDR) {
		return false;
	}
	k->e = e;
	k->n = 4u + body;
	k->ki = be16(e + 5);
	k->kdlen = be16(e + EK_KD_LEN);
	return EK_HDR + k->kdlen <= k->n;
}

static bool
ek_mic_ok(const struct ekey *k, const uint8_t kck[16])
{
	uint8_t copy[EAPOL_MAX], mic[20];
	memcpy(copy, k->e, k->n);
	bzero(copy + EK_MIC, 16u);
	const uint8_t *parts[1] = { copy };
	uint32_t lens[1] = { k->n };
	hmac_sha1(kck, 16u, parts, lens, 1u, mic);
	bool ok = memcmp(mic, k->e + EK_MIC, 16u) == 0;
	bzero(mic, sizeof(mic));
	return ok;
}

/* messages 2 and 4: our EAPOL-Key frame in a native wifi data frame to the access point, unencrypted */
static const char *
send_ek(uint32_t ver, uint32_t ki, const uint8_t replay[8], const uint8_t *nonce, const uint8_t *kd, uint32_t kdlen,
    const uint8_t kck[16], uint32_t *st, char *res, size_t len, bool must_complete = true)
{
	uint8_t f[24u + 8u + EK_HDR + 32u];
	bzero(f, sizeof(f));
	f[0] = 0x08u;
	f[1] = 0x01u;                                   /* data, to DS */
	memcpy(f + 4, gBssid, 6u);
	memcpy(f + 10, gMac, 6u);
	memcpy(f + 16, gBssid, 6u);
	memcpy(f + 24, kLlcEapol, 8u);
	uint8_t *e = f + 32;
	uint32_t n = EK_HDR + kdlen;
	e[0] = (uint8_t)ver;
	e[1] = 3u;
	put_be16(e + 2, n - 4u);
	e[4] = 2u;
	put_be16(e + 5, ki);
	put_be16(e + 7, 0u);                            /* key length 0 (RSN) */
	memcpy(e + EK_REPLAY, replay, 8u);
	if (nonce != NULL) {
		memcpy(e + EK_NONCE, nonce, 32u);
	}
	put_be16(e + EK_KD_LEN, kdlen);
	if (kdlen > 0) {
		memcpy(e + EK_HDR, kd, kdlen);
	}
	uint8_t mic[20];
	const uint8_t *parts[1] = { e };
	uint32_t lens[1] = { n };
	hmac_sha1(kck, 16u, parts, lens, 1u, mic);
	memcpy(e + EK_MIC, mic, 16u);
	bzero(mic, sizeof(mic));
	return htt_tx(f, 32u + n, false, true, st, res, len, must_complete);
}

static bool
wpa_fail(char *res, size_t len, const char *what)
{
	char name[33];
	ssid_print(name, sizeof(name));
	snprintf(res, len, "STEP 6 FAIL: WPA2 with %s: %s", name, what);
	return false;
}

static bool
run6(char *res, size_t len)
{
	gStep = "6";
	char name[33], why[160];
	ssid_print(name, sizeof(name));
	if (gJoinOpen) {
		snprintf(res, len, "STEP 6 PASS: %s is an open network: no keys to agree on", name);
		gAuthorized = true;
		return true;
	}
	const char *bad = crypto_selftest();
	if (bad != NULL) {
		snprintf(why, sizeof(why), "the %s self-test failed", bad);
		return wpa_fail(res, len, why);
	}
	uint32_t t0 = ms_since_power_on();
	uint8_t ptk[48], anonce[32], snonce[32], replay[8], gtk[32];
	uint32_t msg1s = 0, msg2s = 0, gtk_idx = 0, gtk_len = 0, st = 0, ver = 1;
	bool have_ptk = false, done = false, rsn_differs = false;
	bzero(ptk, sizeof(ptk));
	for (uint32_t t = 0; t < 10000u && !done; t++) {
		pump();
		if (gDeauth || gKickout) {
			break;
		}
		if (t % 10u == 0 && fw_down("the 4-way handshake", res, len)) {
			return false;
		}
		if (gEapolHead == gEapolTail) {
			IOSleep(1);
			continue;
		}
		uint32_t slot = gEapolTail % EAPOL_QUEUE;
		struct ekey k;
		bool parsed = ek_parse(gEapolQ[slot], gEapolQLen[slot], &k);
		gEapolTail++;
		if (!parsed || (k.ki & KI_VERSION_MASK) != 2u || !(k.ki & KI_PAIRWISE) || !(k.ki & KI_ACK)) {
			A_LOG("EAPOL frame ignored (key information %04x, %u bytes)", parsed ? k.ki : 0u, gEapolQLen[slot]);
			continue;
		}
		if (!(k.ki & KI_MIC)) {
			/* message 1: ANonce; PTK = PRF-384(PMK, "Pairwise key expansion", min/max addresses, min/max nonces) */
			msg1s++;
			ver = k.e[0];
			memcpy(anonce, k.e + EK_NONCE, 32u);
			memcpy(replay, k.e + EK_REPLAY, 8u);
			read_random(snonce, sizeof(snonce));
			uint64_t now = 0;
			clock_get_uptime(&now);
			for (uint32_t i = 0; i < 8u; i++) {
				snonce[i] ^= (uint8_t)(now >> (8u * i));
			}
			uint8_t data[76];
			bool mac_lo = memcmp(gMac, gBssid, 6u) < 0, nonce_lo = memcmp(snonce, anonce, 32u) < 0;
			memcpy(data, mac_lo ? gMac : gBssid, 6u);
			memcpy(data + 6, mac_lo ? gBssid : gMac, 6u);
			memcpy(data + 12, nonce_lo ? snonce : anonce, 32u);
			memcpy(data + 44, nonce_lo ? anonce : snonce, 32u);
			prf_sha1(kOp2WifiPmk, 32u, "Pairwise key expansion", data, sizeof(data), ptk, 48u);
			have_ptk = true;
			const char *e = send_ek(ver, 2u | KI_PAIRWISE | KI_MIC, replay, snonce, kOurRsn, sizeof(kOurRsn), ptk, &st,
			    res, len);
			if (e != NULL) {
				bzero(ptk, sizeof(ptk));
				return gFwDown ? false : wpa_fail(res, len, e);
			}
			msg2s++;
			A_LOG("message 1 of 4 (replay counter %02x%02x, EAPOL version %u) answered with message 2: %s",
			    replay[6], replay[7], ver, tx_status_name(st));
			continue;
		}
		/* message 3: same ANonce, MIC with our KCK, newer replay counter, the GTK in the encrypted key data */
		if (!have_ptk || memcmp(k.e + EK_NONCE, anonce, 32u) != 0 || memcmp(k.e + EK_REPLAY, replay, 8u) <= 0) {
			A_LOG("%s", "message 3 ignored: no message 1 before it, another ANonce or an old replay counter");
			continue;
		}
		if (!ek_mic_ok(&k, ptk)) {
			A_LOG("%s", "message 3 ignored: its MIC does not match (another password on this side?)");
			continue;
		}
		if ((k.ki & (KI_INSTALL | KI_SECURE | KI_ENC_KEY_DATA)) != (KI_INSTALL | KI_SECURE | KI_ENC_KEY_DATA)) {
			snprintf(why, sizeof(why), "message 3 has key information %04x (install, secure, encrypted key data "
			    "expected)", k.ki);
			bzero(ptk, sizeof(ptk));
			return wpa_fail(res, len, why);
		}
		uint8_t kd[EAPOL_MAX];
		if (k.kdlen < 24u || !aes_unwrap(ptk + 16, k.e + EK_HDR, k.kdlen, kd)) {
			bzero(ptk, sizeof(ptk));
			return wpa_fail(res, len, "message 3's key data does not decrypt (AES key unwrap check failed)");
		}
		uint32_t kdn = k.kdlen - 8u;
		for (uint32_t o = 0; o + 2u <= kdn;) {
			uint32_t id = kd[o], l = kd[o + 1u];
			if (o + 2u + l > kdn || (id == 0xDDu && l == 0)) {
				break;   /* padding */
			}
			if (id == 48u) {
				rsn_differs = l != gAp.rsn_len || memcmp(kd + o + 2, gAp.rsn, l) != 0;
			} else if (id == 0xDDu && l >= 6u + 16u && memcmp(kd + o + 2, "\x00\x0F\xAC\x01", 4u) == 0) {
				gtk_idx = kd[o + 6u] & 3u;
				gtk_len = l - 6u > sizeof(gtk) ? (uint32_t)sizeof(gtk) : l - 6u;
				memcpy(gtk, kd + o + 8, gtk_len);
			}
			o += 2u + l;
		}
		bzero(kd, sizeof(kd));
		if (gtk_len != 16u) {
			bzero(ptk, sizeof(ptk));
			return wpa_fail(res, len, "message 3 carries no CCMP group key");
		}
		memcpy(replay, k.e + EK_REPLAY, 8u);
		/* message 4; its completion is not waited for beyond 2 s: wpa_supplicant installs the keys right after
		 * sending it, and this firmware may not confirm it (it paused tx around message 3 on the phone) */
		const char *e = send_ek(ver, 2u | KI_PAIRWISE | KI_MIC | KI_SECURE, replay, NULL, NULL, 0u, ptk, &st, res, len,
		    false);
		if (e != NULL) {
			bzero(ptk, sizeof(ptk));
			bzero(gtk, sizeof(gtk));
			return gFwDown ? false : wpa_fail(res, len, e);
		}
		A_LOG("message 3 of 4 checked (MIC, group key %u%s); message 4: %s", gtk_idx, rsn_differs ?
		    ", its RSN element DIFFERS from the beacon's" : "", tx_status_name(st));
		done = true;
	}
	uint32_t took = ms_since_power_on() - t0;
	if (!done) {
		bzero(ptk, sizeof(ptk));
		if (gDeauth) {
			snprintf(why, sizeof(why), "it sent %s, reason %u (%s) after %u message 1(s)%s", gDeauthSubtype == 0xC0u ?
			    "a deauthentication" : "a disassociation", gDeauthReason, reason_name(gDeauthReason), msg1s,
			    msg1s > 1u ? ": the password is probably wrong" : "");
		} else if (msg1s == 0) {
			snprintf(why, sizeof(why), "no message 1 within 10 s (%u EAPOL frames, %u data frames from it, %u ring "
			    "data frames, %u in-order indications: %u buffers, %u offloaded, %u unusable)", gEapolRx, gDataFromAp,
			    gRingData, gInOrdInd, gInOrdFrames, gInOrdOffload, gInOrdBad);
		} else {
			snprintf(why, sizeof(why), "%u message 1(s) and %u message 2(s) but no valid message 3 in 10 s: the "
			    "password is probably wrong", msg1s, msg2s);
		}
		return wpa_fail(res, len, why);
	}

	/* ath10k_set_key: pairwise key (index 0), group key (its index), each confirmed by an HTT security indication;
	 * then the port opens (peer param authorize) */
	uint32_t sec0 = gSecInd;
	uint8_t kck[16];
	memcpy(kck, ptk, sizeof(kck));   /* to answer a repeated message 3 (message 4 lost) while connected */
	bool ok = install_key(0u, WMI_KEY_PAIRWISE, ptk + 32);
	bzero(ptk, sizeof(ptk));
	uint32_t sec_want = sec0 + 1u;
	for (uint32_t t = 0; ok && t < 3000u && gSecInd < sec_want; t++) {
		pump();
		IOSleep(1);
	}
	ok = ok && install_key(gtk_idx, WMI_KEY_GROUP, gtk);
	bzero(gtk, sizeof(gtk));
	sec_want = sec0 + 2u;
	for (uint32_t t = 0; ok && t < 3000u && gSecInd < sec_want; t++) {
		pump();
		IOSleep(1);
	}
	ok = ok && peer_set_param(WMI_TLV_PEER_AUTHORIZE, 1u);
	if (!ok) {
		bzero(kck, sizeof(kck));
		return wpa_fail(res, len, "a key or the authorize command could not be sent");
	}
	gAuthorized = true;
	uint32_t confirmed = gSecInd - sec0;
	A_LOG("keys installed (firmware confirmed %u of 2), port open; listening 5 s", confirmed);

	/* 5 s connected: data from the network (decrypted by the chip), no deauthentication; a repeated message 3
	 * means our message 4 was lost: answered again */
	uint32_t msg3_repeats = 0;
	for (uint32_t t = 0; t < 5000u && !gDeauth && !gKickout; t++) {
		pump();
		if (t % 10u == 0 && fw_down("the connection", res, len)) {
			bzero(kck, sizeof(kck));
			return false;
		}
		while (gEapolHead != gEapolTail) {
			uint32_t slot = gEapolTail % EAPOL_QUEUE;
			struct ekey k;
			bool parsed = ek_parse(gEapolQ[slot], gEapolQLen[slot], &k);
			gEapolTail++;
			if (parsed && (k.ki & KI_ACK) && (k.ki & KI_MIC) && (k.ki & KI_INSTALL) &&
			    memcmp(k.e + EK_REPLAY, replay, 8u) > 0 && ek_mic_ok(&k, kck)) {
				msg3_repeats++;
				memcpy(replay, k.e + EK_REPLAY, 8u);
				const char *e = send_ek(ver, 2u | KI_PAIRWISE | KI_MIC | KI_SECURE, replay, NULL, NULL, 0u, kck, &st,
				    res, len, false);
				A_LOG("message 3 repeated (our message 4 was lost?): message 4 again: %s", e != NULL ? e :
				    tx_status_name(st));
			}
		}
		IOSleep(1);
	}
	bzero(kck, sizeof(kck));
	if (gDeauth || gKickout) {
		snprintf(why, sizeof(why), "connected, then %s (reason %u, %s)", gKickout ? "the firmware kicked the access "
		    "point out" : gDeauthSubtype == 0xC0u ? "deauthenticated" : "disassociated", gDeauthReason,
		    reason_name(gDeauthReason));
		return wpa_fail(res, len, why);
	}
	snprintf(res, len, "STEP 6 PASS: WPA2 connected to %s: 4-way handshake in %u ms (message 1 seen %u time(s)%s), "
	    "pairwise and group key %u installed (firmware confirmed %u of 2), port open; %u data frames from the network "
	    "in 5 s%s, no deauthentication", name, took, msg1s, msg3_repeats ? ", message 3 repeated" : "", gtk_idx,
	    confirmed, gDataAfterKeys, gRoam ? ", firmware reported beacon loss" : "");
	return true;
}

/* ---- step 7: data through the keys - DHCP with the network (RFC 2131), then ARP and ping its router ---- */

#define ETH_IPV4                          0x0800u
#define ETH_ARP                           0x0806u
#define DHCP_DISCOVER                     1u
#define DHCP_OFFER                        2u
#define DHCP_REQUEST                      3u
#define DHCP_ACK                          5u
#define DHCP_NAK                          6u
#define PING_COUNT                        3u

static const uint8_t kBcast[6] = { 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF };
static uint32_t gXid, gMyIp, gServerIp, gRouterIp, gNetmask, gDns, gLease;   /* addresses big-endian in a uint32 */
static uint32_t gDhcpGot, gDhcpType, gOfferIp, gOfferServer, gIpFrames, gArpFrames, gArpAnswered, gOtherIp;
static uint8_t gRouterMac[6];
static bool gRouterMacKnown;
static uint32_t gPingSeqSeen[PING_COUNT], gPingRtt[PING_COUNT], gPingSentAt[PING_COUNT];
static const uint16_t kPingId = 0x4F32;   /* "O2" */

static inline uint32_t
rd_be32(const uint8_t *p)
{
	return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3];
}

static inline void
wr_be32(uint8_t *p, uint32_t v)
{
	p[0] = (uint8_t)(v >> 24);
	p[1] = (uint8_t)(v >> 16);
	p[2] = (uint8_t)(v >> 8);
	p[3] = (uint8_t)v;
}

static uint32_t
ip_sum(const uint8_t *p, uint32_t n)   /* the Internet checksum (RFC 1071) */
{
	uint32_t s = 0;
	for (uint32_t i = 0; i + 1u < n; i += 2u) {
		s += be16(p + i);
	}
	if (n & 1u) {
		s += (uint32_t)p[n - 1u] << 8;
	}
	while (s >> 16) {
		s = (s & 0xFFFFu) + (s >> 16);
	}
	return ~s & 0xFFFFu;
}

static void
ip_str(uint32_t ip, char out[16])
{
	snprintf(out, 16, "%u.%u.%u.%u", ip >> 24, (ip >> 16) & 0xFFu, (ip >> 8) & 0xFFu, ip & 0xFFu);
}

/* An Ethernet-type payload to dst as a native wifi data frame to the access point: to DS, Protected (the chip adds
 * CCMP with the installed pairwise key, as mac80211 marks frames for ath10k), LLC/SNAP + ethertype. */
static const char *
send_eth(const uint8_t dst[6], uint32_t ethertype, const uint8_t *payload, uint32_t plen, char *res, size_t len)
{
	uint8_t f[24u + 8u + 600u];
	if (plen > 600u) {
		return "payload too long";
	}
	bzero(f, 32u);
	f[0] = 0x08u;
	f[1] = 0x01u | 0x40u;                             /* to DS, Protected */
	memcpy(f + 4, gBssid, 6u);
	memcpy(f + 10, gMac, 6u);
	memcpy(f + 16, dst, 6u);
	put16(f + 22, (uint32_t)(gSeq++ & 0xFFFu) << 4);
	f[24] = 0xAAu;
	f[25] = 0xAAu;
	f[26] = 0x03u;
	put_be16(f + 30, ethertype);
	memcpy(f + 32, payload, plen);
	uint32_t st = 0;
	const char *e = htt_tx(f, 32u + plen, false, false, &st, res, len, false);
	return e;
}

/* IPv4 + UDP (checksum 0: optional over IPv4) */
static uint32_t
build_udp(uint8_t *p, uint32_t src, uint32_t dst, uint32_t sport, uint32_t dport, const uint8_t *data, uint32_t dlen)
{
	uint32_t total = 20u + 8u + dlen;
	bzero(p, 28u);
	p[0] = 0x45u;
	put_be16(p + 2, total);
	put_be16(p + 4, gSeq);                            /* identification */
	p[8] = 64u;
	p[9] = 17u;
	wr_be32(p + 12, src);
	wr_be32(p + 16, dst);
	put_be16(p + 10, ip_sum(p, 20u));
	put_be16(p + 20, sport);
	put_be16(p + 22, dport);
	put_be16(p + 24, 8u + dlen);
	memcpy(p + 28, data, dlen);
	return total;
}

static const char *
dhcp_send(uint32_t type, char *res, size_t len)
{
	uint8_t b[300], pkt[340];
	bzero(b, sizeof(b));
	b[0] = 1u;                                        /* BOOTREQUEST, Ethernet, 6-byte address */
	b[1] = 1u;
	b[2] = 6u;
	wr_be32(b + 4, gXid);
	put_be16(b + 10, 0x8000u);                        /* broadcast: we cannot take unicast before having the address */
	memcpy(b + 28, gMac, 6u);
	wr_be32(b + 236, 0x63825363u);                    /* magic cookie */
	uint32_t o = 240u;
	b[o++] = 53; b[o++] = 1; b[o++] = (uint8_t)type;
	b[o++] = 61; b[o++] = 7; b[o++] = 1;
	memcpy(b + o, gMac, 6u);
	o += 6u;
	if (type == DHCP_REQUEST) {
		b[o++] = 50; b[o++] = 4; wr_be32(b + o, gOfferIp); o += 4u;
		b[o++] = 54; b[o++] = 4; wr_be32(b + o, gOfferServer); o += 4u;
	}
	b[o++] = 57; b[o++] = 2; put_be16(b + o, 1500u); o += 2u;
	b[o++] = 55; b[o++] = 4; b[o++] = 1; b[o++] = 3; b[o++] = 6; b[o++] = 51;
	b[o++] = 255;
	uint32_t n = build_udp(pkt, 0u, 0xFFFFFFFFu, 68u, 67u, b, sizeof(b));
	return send_eth(kBcast, ETH_IPV4, pkt, n, res, len);
}

static void
on_dhcp(const uint8_t *b, uint32_t n)
{
	if (n < 240u || b[0] != 2u || rd_be32(b + 4) != gXid || rd_be32(b + 236) != 0x63825363u ||
	    memcmp(b + 28, gMac, 6u) != 0) {
		return;
	}
	uint32_t type = 0, server = 0, mask = 0, router = 0, dns = 0, lease = 0;
	for (uint32_t o = 240u; o < n && b[o] != 255;) {
		if (b[o] == 0) {
			o++;
			continue;
		}
		if (o + 2u > n || o + 2u + b[o + 1u] > n) {
			break;
		}
		uint32_t id = b[o], l = b[o + 1u];
		const uint8_t *v = b + o + 2u;
		if (id == 53 && l >= 1u) type = v[0];
		if (id == 54 && l >= 4u) server = rd_be32(v);
		if (id == 1 && l >= 4u) mask = rd_be32(v);
		if (id == 3 && l >= 4u) router = rd_be32(v);
		if (id == 6 && l >= 4u) dns = rd_be32(v);
		if (id == 51 && l >= 4u) lease = rd_be32(v);
		o += 2u + l;
	}
	if (type == DHCP_OFFER && gDhcpType == 0) {
		gOfferIp = rd_be32(b + 16);
		gOfferServer = server;
		gDhcpType = DHCP_OFFER;
	} else if ((type == DHCP_ACK || type == DHCP_NAK) && gDhcpType == DHCP_OFFER) {
		gDhcpType = type;
		if (type == DHCP_ACK) {
			gMyIp = rd_be32(b + 16);
			gServerIp = server;
			gNetmask = mask;
			gRouterIp = router;
			gDns = dns;
			gLease = lease;
		}
	}
	gDhcpGot++;
}

/* everything IPv4 / ARP that reaches us: DHCP replies, ARP (answered when it asks for our address), ping replies */
static void
on_ip(uint32_t ethertype, const uint8_t *p, uint32_t n, const uint8_t *da, const uint8_t *sa)
{
	(void)da;
	if (ethertype == ETH_ARP && n >= 28u && be16(p) == 1u && be16(p + 2) == ETH_IPV4 && p[4] == 6u && p[5] == 4u) {
		gArpFrames++;
		uint32_t op = be16(p + 6), spa = rd_be32(p + 14), tpa = rd_be32(p + 24);
		if (op == 2u && gRouterIp != 0 && spa == gRouterIp) {
			memcpy(gRouterMac, p + 8, 6u);
			gRouterMacKnown = true;
		} else if (op == 1u && gMyIp != 0 && tpa == gMyIp) {
			uint8_t r[28];
			memcpy(r, p, 6u);
			put_be16(r + 6, 2u);
			memcpy(r + 8, gMac, 6u);
			wr_be32(r + 14, gMyIp);
			memcpy(r + 18, p + 8, 6u);
			wr_be32(r + 24, spa);
			char res[96];
			if (send_eth(sa, ETH_ARP, r, sizeof(r), res, sizeof(res)) == NULL) {
				gArpAnswered++;
			}
		}
		return;
	}
	if (ethertype != ETH_IPV4 || n < 20u || (p[0] >> 4) != 4u) {
		gOtherIp++;
		return;
	}
	gIpFrames++;
	uint32_t ihl = (p[0] & 0xFu) * 4u, total = be16(p + 2);
	if (ihl < 20u || total > n || total < ihl) {
		return;
	}
	const uint8_t *l4 = p + ihl;
	uint32_t l4n = total - ihl;
	if (p[9] == 17u && l4n >= 8u && be16(l4) == 67u && be16(l4 + 2) == 68u) {
		on_dhcp(l4 + 8, l4n - 8u);
	} else if (p[9] == 1u && l4n >= 8u && l4[0] == 0 && be16(l4 + 4) == kPingId && gMyIp != 0 &&
	    rd_be32(p + 16) == gMyIp) {
		uint32_t seq = be16(l4 + 6);
		if (seq >= 1u && seq <= PING_COUNT && gPingSeqSeen[seq - 1u] == 0) {
			gPingSeqSeen[seq - 1u] = 1u;
			gPingRtt[seq - 1u] = ms_since_power_on() - gPingSentAt[seq - 1u];
		}
	}
}

static bool
data_fail(char *res, size_t len, const char *what)
{
	char name[33];
	ssid_print(name, sizeof(name));
	snprintf(res, len, "STEP 7 FAIL: data with %s: %s (%u IPv4 and %u ARP frames from it after the keys, %u other)", name,
	    what, gIpFrames, gArpFrames, gOtherIp);
	return false;
}

static bool
run7(char *res, size_t len)
{
	gStep = "7";
	char name[33];
	ssid_print(name, sizeof(name));
	uint32_t t0 = ms_since_power_on();
	read_random(&gXid, sizeof(gXid));
	gIpHook = on_ip;

	/* DHCP: DISCOVER until an OFFER (4 tries, 2 s each), then REQUEST until an ACK or NAK */
	for (uint32_t i = 0; i < 4u && gDhcpType == 0; i++) {
		const char *e = dhcp_send(DHCP_DISCOVER, res, len);
		if (e != NULL) {
			return gFwDown ? false : data_fail(res, len, e);
		}
		A_LOG("DHCP discover %u sent (encrypted, broadcast)", i + 1u);
		(void)wait_for([]() { return gDhcpType != 0 || gDeauth || gKickout; }, 2000u, "a DHCP offer", res, len);
		if (gFwDown) {
			return false;
		}
	}
	if (gDeauth || gKickout) {
		return data_fail(res, len, gKickout ? "the firmware dropped the access point" : "it deauthenticated us");
	}
	if (gDhcpType == 0) {
		return data_fail(res, len, "no DHCP offer to 4 discovers");
	}
	char a[16], b[16], c[16], d[16];
	ip_str(gOfferIp, a);
	ip_str(gOfferServer, b);
	A_LOG("DHCP offer: %s from %s (the first encrypted frame from the network decrypted by the chip)", a, b);
	for (uint32_t i = 0; i < 4u && gDhcpType == DHCP_OFFER; i++) {
		const char *e = dhcp_send(DHCP_REQUEST, res, len);
		if (e != NULL) {
			return gFwDown ? false : data_fail(res, len, e);
		}
		(void)wait_for([]() { return gDhcpType != DHCP_OFFER || gDeauth; }, 2000u, "a DHCP ack", res, len);
		if (gFwDown) {
			return false;
		}
	}
	if (gDhcpType != DHCP_ACK) {
		return data_fail(res, len, gDhcpType == DHCP_NAK ? "the DHCP server refused our request (NAK)" :
		    "no DHCP ack to 4 requests");
	}
	uint32_t dhcp_ms = ms_since_power_on() - t0;
	uint32_t prefix = 0;
	for (uint32_t m = gNetmask; m & 0x80000000u; m <<= 1) {
		prefix++;
	}
	ip_str(gMyIp, a);
	ip_str(gRouterIp, b);
	ip_str(gDns, c);
	ip_str(gServerIp, d);
	A_LOG("DHCP ack: %s/%u, router %s, DNS %s, server %s, lease %u s (%u ms)", a, prefix, b, c, d, gLease, dhcp_ms);

	/* ARP for the router, then ping it 3 times, 1 s apart */
	uint32_t replies = 0, rmin = 0xFFFFFFFFu, rmax = 0, rsum = 0;
	if (gRouterIp != 0) {
		for (uint32_t i = 0; i < 3u && !gRouterMacKnown; i++) {
			uint8_t r[28];
			bzero(r, sizeof(r));
			put_be16(r, 1u);
			put_be16(r + 2, ETH_IPV4);
			r[4] = 6u;
			r[5] = 4u;
			put_be16(r + 6, 1u);
			memcpy(r + 8, gMac, 6u);
			wr_be32(r + 14, gMyIp);
			wr_be32(r + 24, gRouterIp);
			(void)send_eth(kBcast, ETH_ARP, r, sizeof(r), res, len);
			(void)wait_for([]() { return gRouterMacKnown; }, 1000u, "an ARP reply", res, len);
			if (gFwDown) {
				return false;
			}
		}
		for (uint32_t seq = 1; gRouterMacKnown && seq <= PING_COUNT; seq++) {
			uint8_t icmp[8u + 32u], pkt[20u + sizeof(icmp)];
			bzero(icmp, sizeof(icmp));
			icmp[0] = 8u;                             /* echo request */
			put_be16(icmp + 4, kPingId);
			put_be16(icmp + 6, seq);
			for (uint32_t i = 8; i < sizeof(icmp); i++) {
				icmp[i] = (uint8_t)('a' + (i - 8u) % 23u);
			}
			put_be16(icmp + 2, ip_sum(icmp, sizeof(icmp)));
			bzero(pkt, 20u);
			pkt[0] = 0x45u;
			put_be16(pkt + 2, sizeof(pkt));
			put_be16(pkt + 4, gSeq);
			pkt[8] = 64u;
			pkt[9] = 1u;
			wr_be32(pkt + 12, gMyIp);
			wr_be32(pkt + 16, gRouterIp);
			put_be16(pkt + 10, ip_sum(pkt, 20u));
			memcpy(pkt + 20, icmp, sizeof(icmp));
			gPingSentAt[seq - 1u] = ms_since_power_on();
			(void)send_eth(gRouterMac, ETH_IPV4, pkt, sizeof(pkt), res, len);
			for (uint32_t t = 0; t < 1000u; t++) {
				pump();
				if (t % 10u == 0 && fw_down("a ping reply", res, len)) {
					return false;
				}
				IOSleep(1);
			}
		}
		for (uint32_t i = 0; i < PING_COUNT; i++) {
			if (gPingSeqSeen[i]) {
				replies++;
				rsum += gPingRtt[i];
				rmin = gPingRtt[i] < rmin ? gPingRtt[i] : rmin;
				rmax = gPingRtt[i] > rmax ? gPingRtt[i] : rmax;
			}
		}
	}
	char ping[96];
	if (!gRouterMacKnown) {
		snprintf(ping, sizeof(ping), "no ARP reply from the router %s", b);
	} else if (replies == 0) {
		snprintf(ping, sizeof(ping), "ping %s: 0 of %u replies", b, PING_COUNT);
	} else {
		snprintf(ping, sizeof(ping), "ping %s: %u of %u replies, %u/%u/%u ms", b, replies, PING_COUNT, rmin,
		    rsum / replies, rmax);
	}
	snprintf(res, len, "STEP 7 PASS: data through WPA2 with %s: DHCP lease %s/%u (router %s, DNS %s, %u s) in %u ms; "
	    "%s; %u ARP requests for us answered", name, a, prefix, b, c, gLease, dhcp_ms, ping, gArpAnswered);
	return true;
}

/* ---- step 8: wl0, a network interface for iOS (bsd/dev/op2_wlan.c), on the lease of step 7; stays connected ----
 * Ethernet frames from iOS's stack go out as native wifi data frames (to DS, Protected: the chip encrypts them),
 * up to TXS_COUNT in flight, each in its own DMA slot until its TX_COMPL_IND. Data frames from the network (IPv4,
 * ARP, IPv6, anything with LLC/SNAP) go to the stack as Ethernet frames; iOS answers ARP for its address itself.
 * Still polled (no interrupts): the loop sleeps 1 ms while there is traffic, 3 ms after a second of quiet. */

#define ETH_HDR                           14u
#define ETH_MAX                           1514u    /* header + 1500 */

static uint32_t gTxsBusy;                 /* slots waiting for their completion */
static uint32_t gTxsAt[TXS_COUNT];
static uint32_t gTxsAcked, gTxsNoAck, gTxsDiscarded, gTxsLost, gTxsFrames, gTxsBytes, gTxsDropped;
static uint32_t gWlRx, gWlRxBytes, gWlRxOwn, gBeaconMiss;
static uint32_t gTxsSendFails;
static bool gWlUp;

static void
txs_done(uint32_t slot, uint32_t status)
{
	if (slot >= TXS_COUNT || !(gTxsBusy & (1u << slot))) {
		return;
	}
	gTxsBusy &= ~(1u << slot);
	if (status == 0) {
		gTxsAcked++;
	} else if (status == 2u) {
		gTxsNoAck++;
	} else {
		gTxsDiscarded++;
	}
}

/* one native wifi data frame into a free slot and onto CE4; false if no slot or CE4 is full */
static bool
txs_send(const uint8_t *frame, uint32_t flen)
{
	uint32_t i = 0;
	while (i < TXS_COUNT && (gTxsBusy & (1u << i))) {
		i++;
	}
	if (i == TXS_COUNT || flen > TXS_SIZE - TXS_FRAME || flen < 24u) {
		return false;
	}
	uint8_t *t = gDma + OFF_TXS + i * TXS_SIZE, *f = t + TXS_FRAME;
	uint32_t tpa = gDmaPhys + OFF_TXS + i * TXS_SIZE, fpa = tpa + TXS_FRAME;
	memcpy(f, frame, flen);
	bzero(t, TXS_FRAME);
	put32(t, fpa);                                    /* frags[0] = the frame; frags[1] = 0, 0 ends the list */
	put32(t + 4, flen);
	uint32_t pre = ((flen < HTT_TX_PREFETCH ? flen : HTT_TX_PREFETCH) + 3u) & ~3u;
	t[16] = gEpHtt;                                   /* HTC header: endpoint, no flags, length */
	put16(t + 18, 16u + pre);
	t[24] = HTT_H2T_MSG_TYPE_TX_FRM;
	t[25] = (uint8_t)(HTT_TX_FLAGS0_MAC_HDR_PRESENT | (HTT_TX_PKT_NATIVE_WIFI << 5));
	put16(t + 26, (HTT_TX_EXT_TID_NON_QOS << 6) | HTT_TX_FLAGS1_POSTPONED);   /* vdev 0 */
	put16(t + 28, flen);
	put16(t + 30, TXS_ID_BASE + i);
	put32(t + 32, tpa);
	put16(t + 36, 0xFFFFu);                           /* offchan_tx: HTT_INVALID_PEERID, freq 0 */
	put16(t + 38, 0u);
	dma_fence();
	if (!ce_send2(&gCe4, tpa + 16u, 24u, fpa, pre)) {
		return false;
	}
	gTxsBusy |= 1u << i;
	gTxsAt[i] = ms_since_power_on();
	return true;
}

/* room on CE4 for one more frame (two descriptors, one entry kept free as ce_send2 does) */
static bool
ce4_room(void)
{
	struct ce_ring *r = &gCe4.src;
	return ((r->sw_index - 1u - r->write_index) & (r->nentries - 1u)) >= 2u;
}

/* CE4 descriptors the copy engine has finished with; slots whose completion never came */
static void
txs_reap(void)
{
	while (ce_send_done(&gCe4)) {
	}
	bwr(gCe4.base + CE_HOST_IS, 0x1Fu);
	uint32_t now = ms_since_power_on();
	for (uint32_t i = 0; i < TXS_COUNT; i++) {
		if ((gTxsBusy & (1u << i)) && now - gTxsAt[i] > TXS_TIMEOUT_MS) {
			gTxsBusy &= ~(1u << i);
			gTxsLost++;
		}
	}
}

/* from the network (join_data, after the keys): an Ethernet frame for iOS's stack */
static void
wl_rx(uint32_t ethertype, const uint8_t *p, uint32_t n, const uint8_t *da, const uint8_t *sa)
{
	static uint8_t e[ETH_MAX];
	if (!gWlUp) {
		return;
	}
	if (memcmp(sa, gMac, 6u) == 0) {
		gWlRxOwn++;                                   /* our own broadcast, repeated by the access point */
		return;
	}
	if (n > ETH_MAX - ETH_HDR) {
		n = ETH_MAX - ETH_HDR;
	}
	memcpy(e, da, 6u);
	memcpy(e + 6, sa, 6u);
	put_be16(e + 12, ethertype);
	memcpy(e + ETH_HDR, p, n);
	op2_wlan_input(e, ETH_HDR + n);
	gWlRx++;
	gWlRxBytes += ETH_HDR + n;
}

/* to the network: an Ethernet frame from the stack as a native wifi data frame (to DS, Protected) */
static bool
wl_tx(const uint8_t *e, uint32_t n)
{
	static uint8_t f[32u + ETH_MAX];
	uint32_t type = be16(e + 12);
	if (n < ETH_HDR || type < 0x0600u) {             /* 802.3 length field: not Ethernet II */
		gTxsDropped++;
		return true;
	}
	uint32_t plen = n - ETH_HDR;
	bzero(f, 32u);
	f[0] = 0x08u;
	f[1] = 0x01u | 0x40u;                             /* to DS, Protected */
	memcpy(f + 4, gBssid, 6u);
	memcpy(f + 10, gMac, 6u);
	memcpy(f + 16, e, 6u);                            /* DA */
	put16(f + 22, (uint32_t)(gSeq++ & 0xFFFu) << 4);
	f[24] = 0xAAu;
	f[25] = 0xAAu;
	f[26] = 0x03u;
	put_be16(f + 30, type);
	memcpy(f + 32, e + ETH_HDR, plen);
	if (!txs_send(f, 32u + plen)) {
		return false;
	}
	gTxsFrames++;
	gTxsBytes += n;
	return true;
}

static void
wl_status(char *out, size_t n, uint32_t up_s)
{
	snprintf(out, n, "wl0 up %u s: %u frames (%u KB) to iOS, %u frames (%u KB) from iOS (%u acknowledged, %u not, "
	    "%u discarded, %u unconfirmed; %u dropped, %u queue drops, %u send failures); %u beacon-loss events",
	    up_s, gWlRx, gWlRxBytes / 1024u, gTxsFrames, gTxsBytes / 1024u, gTxsAcked, gTxsNoAck, gTxsDiscarded, gTxsLost,
	    gTxsDropped, op2_wlan_drops(), gTxsSendFails, gBeaconMiss);
}

static bool
run8(char *res, size_t len, uint32_t stay_ms)
{
	gStep = "8";
	char a[16], b[16], c[16];
	ip_str(gMyIp, a);
	ip_str(gRouterIp, b);
	ip_str(gDns, c);
	uint32_t prefix = 0;
	for (uint32_t m = gNetmask; m & 0x80000000u; m <<= 1) {
		prefix++;
	}
	int err = op2_wlan_attach(gMac);
	if (err != 0) {
		snprintf(res, len, "STEP 8 FAIL: wl0 could not be created (error %d)", err);
		return false;
	}
	gIpHook = wl_rx;   /* from here on iOS's stack sees everything (and answers ARP) */
	gWlUp = true;
	err = op2_wlan_up(gMyIp, gNetmask, gRouterIp, gDns);
	if (err != 0) {
		gWlUp = false;
		gIpHook = NULL;
		snprintf(res, len, "STEP 8 FAIL: wl0 could not be given %s/%u (error %d)", a, prefix, err);
		return false;
	}
	A_LOG("STEP 8 PASS: wl0 up with %s/%u (router %s, DNS %s): iOS can use it once op2shell publishes it; staying "
	    "connected, a status line every 60 s", a, prefix, b, c);
	/* op2shell publishes wl0 to configd: without it iOS has no route or DNS on wl0. Its boot-time line is long out of
	 * the ramoops ring by now, so say here (and again whenever it changes) what the kernel's check did. */
	static char shell[256], shell_was[256];
	bzero(shell, sizeof(shell));
	op2_shell_status(shell, sizeof(shell));
	A_LOG("op2shell: %s", shell);
	memcpy(shell_was, shell, sizeof(shell));
	uint32_t t0 = ms_since_power_on(), last = t0, next_report = t0 + 60000u, roams = 0, rx_seen = gWlRx;
	static uint8_t e[ETH_MAX];
	const char *why = NULL;
	for (uint32_t it = 0;; it++) {
		pump();
		txs_reap();
		bool busy = false;
		while (gTxPausedIds == 0 && gTxsBusy != (1u << TXS_COUNT) - 1u && ce4_room()) {
			uint32_t n = op2_wlan_dequeue(e, sizeof(e));
			if (n == 0) {
				break;
			}
			busy = true;
			if (!wl_tx(e, n)) {
				gTxsSendFails++;   /* cannot happen (slot and room checked); counted in case it does */
				break;
			}
		}
		uint32_t now = ms_since_power_on();
		if (busy || gTxsBusy != 0 || gWlRx != rx_seen) {
			last = now;
			rx_seen = gWlRx;
		}
		if (gRoam) {
			gRoam = false;
			gBeaconMiss++;
			if (roams++ < 4u) {
				A_LOG("firmware roam event, reason %u (1: beacon loss) after %u s; still associated", gRoamReason,
				    (now - t0) / 1000u);
			}
		}
		if (gDeauth || gKickout) {
			why = gKickout ? "the firmware dropped the access point (station kickout: it stopped answering)" :
			    gDeauthSubtype == 0xA0u ? "the network disassociated us" : "the network deauthenticated us";
			break;
		}
		if (it % 16u == 0 && fw_down("traffic on wl0", res, len)) {
			gWlUp = false;
			op2_wlan_down();
			return false;
		}
		if ((int32_t)(now - next_report) >= 0) {
			char st[240];
			wl_status(st, sizeof(st), (now - t0) / 1000u);
			A_LOG("%s", st);
			bzero(shell, sizeof(shell));
			op2_shell_status(shell, sizeof(shell));
			if (memcmp(shell, shell_was, sizeof(shell)) != 0) {
				A_LOG("op2shell: %s", shell);
				memcpy(shell_was, shell, sizeof(shell));
			}
			next_report += 60000u;
		}
		if (stay_ms != 0 && now - t0 >= stay_ms) {
			why = "the time set for this run ended";
			break;
		}
		IOSleep(now - last < 1000u ? 1u : 3u);
	}
	uint32_t up_s = (ms_since_power_on() - t0) / 1000u;
	gWlUp = false;
	gIpHook = NULL;
	op2_wlan_down();
	for (uint32_t t = 0; t < 500u && gTxsBusy != 0; t++) {   /* let the frames in flight finish before leaving */
		pump();
		txs_reap();
		IOSleep(1);
	}
	txs_reap();
	char st[240];
	wl_status(st, sizeof(st), up_s);
	if (gDeauth && !gKickout) {
		snprintf(res, len, "STEP 8 PASS: %s; then %s (reason %u, %s)", st, why, gDeauthReason, reason_name(gDeauthReason));
	} else {
		snprintf(res, len, "STEP 8 PASS: %s; then %s", st, why);
	}
	return true;
}

/* Leave politely: deauthenticate (reason 3), vdev down, peer delete, vdev stop - whatever was set up. */
static void
leave(void)
{
	if (gFwDown || !gVdevStarted) {
		return;
	}
	gStep = "end";
	char res[160];
	uint32_t st = 0;
	if (gAssociated && !gDeauth) {
		uint8_t f[32];
		uint32_t n = mgmt_hdr(f, 0xC0u);
		put16(f + n, 3u);
		const char *e = htt_tx(f, n + 2u, true, false, &st, res, sizeof(res));
		A_LOG("deauthentication (leaving): %s", e != NULL ? e : tx_status_name(st));
	}
	gAuthorized = false;
	bool ok = (!gVdevUp || vdev_simple(WMI_TLV_VDEV_DOWN_CMDID, WMI_TLV_TAG_VDEV_DOWN_CMD)) &&
	    (!gPeerCreated || peer_cmd(WMI_TLV_PEER_DELETE_CMDID, WMI_TLV_TAG_PEER_DELETE_CMD, false)) &&
	    vdev_simple(WMI_TLV_VDEV_STOP_CMDID, WMI_TLV_TAG_VDEV_STOP_CMD);
	bool stopped = ok && wait_for([]() { return gVdevStopped; }, 2000u, "the vdev stop", res, sizeof(res));
	A_LOG("left the network: vdev down, peer delete, vdev stop %s; %u management frames and %u data frames from "
	    "elsewhere ignored, %u EAPOL frames (%u dropped)", !ok ? "NOT sent" : stopped ? "confirmed" : "unconfirmed",
	    gMgmtOther, gDataOther, gEapolRx, gEapolDropped);
	gMgmtHook = NULL;
	gDataHook = NULL;
	gIpHook = NULL;
	gDrainHook = NULL;
}

static bool
rom_usable(const char *tag, uint32_t fwi, char *res, size_t len)
{
	if (fwi == 0xFFFFFFFFu) {
		snprintf(res, len, "STEP 2b FAIL (%s): BAR0 reads all ones while waiting for the boot ROM", tag);
		return false;
	}
	if (fwi & Q_FW_IND_EVENT_PENDING) {
		snprintf(res, len, "STEP 2b FAIL (%s): chip reports a crash (fw indicator %08x)", tag, fwi);
		return false;
	}
	return true;
}

static bool
run(char *res, size_t len)
{
	if (!q_wake()) {
		snprintf(res, len, "STEP 2b FAIL: chip SoC did not wake (rtc_state %08x)", brd(Q_RTC_STATE));
		return false;
	}
	dump_chip("start");

	/* 1. DMA block (below 4 GB: 32-bit descriptors), chip ASPM off, bus mastering + interrupt disable. */
	IOPhysicalAddress phys = 0;
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
	void *cached = IOMallocContiguous(DMA_SIZE, 4096, &phys);
#pragma clang diagnostic pop
	if (cached == NULL || phys == 0 || (uint64_t)phys + DMA_SIZE > 0x100000000ULL) {
		snprintf(res, len, "STEP 2b FAIL: no DMA block below 4 GB (va %p phys %llx)", cached, (unsigned long long)phys);
		return false;
	}
	gDmaPhys = (uint32_t)phys;
	if (!dma_clear_of_window(res, len)) {
		return false;
	}
	cache_flush(cached, DMA_SIZE);   /* nothing of the cacheable alias may be written back later */
	gDma = (uint8_t *)ml_io_map_wcomb(gDmaPhys, DMA_SIZE);
	if (gDma == NULL) {
		snprintf(res, len, "STEP 2b FAIL: no non-cacheable mapping for the DMA block at %08x", gDmaPhys);
		return false;
	}
	bzero(gDma, DMA_SIZE);
	dma_fence();
	A_LOG("DMA block %u KB at phys %08x (non-cacheable va %p); core_ctrl %08x", DMA_SIZE / 1024u, gDmaPhys,
	    (void *)gDma, brd(Q_CORE_CTRL));
	uint32_t cap = chip_pcie_cap();
	if (cap != 0) {
		uint32_t lc = rd32(gConf, cap + 0x10u);
		if (lc & 3u) {
			wr32(gConf, cap + 0x10u, lc & 0xFFFCu);   /* ASPM off (ath10k_pci_hif_power_up); 0s to LNKSTA */
		}
		A_LOG("chip PCIe capability at %02x: lnkctl %04x -> %04x", cap, lc & 0xFFFFu, rd32(gConf, cap + 0x10u) & 0xFFFFu);
	}
	command_on();

	/* 2. Wait for "initialized" the way ath10k does, then rings and a first attempt without any reset. */
	uint32_t fwi = 0;
	(void)wait_rom("power-on", 3000u, &fwi);
	if (!rom_usable("power-on", fwi, res, len)) {
		return false;
	}
	init_rings(true);
	bool silent = false;
	if (attempt("no reset", res, len, &silent) || !silent) {
		return strncmp(res, "STEP 2b PASS", 12) == 0;
	}

	/* 3. BMI silent: the cold reset ath10k does on every QCA6174 power-up (ath10k_pci_qca6174_chip_reset). */
	if (gColdReset == NULL) {
		return false;
	}
	A_LOG("%s", "BMI silent: cold reset (SOC_GLOBAL_RESET, the whole chip; link and config space checked)");
	char why[120];
	if (!gColdReset(why, sizeof(why))) {
		gChipGone = true;
		snprintf(res, len, "STEP 2b FAIL: BMI silent, then the cold reset failed: %s", why);
		return false;
	}
	command_on();   /* the reset may have cleared the chip's command register */
	if (!dma_clear_of_window(res, len)) {
		return false;
	}
	(void)wait_rom("after cold reset", 3000u, &fwi);
	if (!rom_usable("after cold reset", fwi, res, len)) {
		return false;
	}
	init_rings(false);
	return attempt("after cold reset", res, len, &silent);
}

extern "C" bool
op2_ath10k_step2b(const struct op2_ath10k_bus *bus, char *result, size_t len)
{
	gB = bus->bar0;
	gConf = bus->conf;
	gDbi = bus->dbi;
	gPowerOnAbs = bus->power_on_abs;
	gColdReset = bus->cold_reset;
	bool ok = run(result, len);
	if (ok && bus->boot_firmware) {
		A_LOG("%s", result);   /* the 2b verdict; the result line becomes 2c's */
		ok = run2c(result, len);
	}
	if (ok && bus->start_services) {
		A_LOG("%s", result);   /* the 2c verdict; the result line becomes step 3's */
		ok = run3(result, len);
	}
	if (ok && bus->scan) {
		A_LOG("%s", result);   /* the step 3 verdict; the result line becomes step 4's */
		ok = run4(result, len);
	}
	if (ok && bus->join) {
		A_LOG("%s", result);   /* the step 4 verdict (network list above); the result line becomes step 5's */
		ok = run5(result, len);
		if (ok && bus->wpa2) {
			A_LOG("%s", result);
			ok = run6(result, len);
		}
		if (ok && bus->data) {
			A_LOG("%s", result);
			ok = run7(result, len);
		}
		if (ok && bus->iface) {
			A_LOG("%s", result);
			ok = run8(result, len, bus->iface_ms);
		}
		leave();
	}
	/* The chip cannot DMA any more; the block stays allocated for good. */
	if (!gChipGone) {
		bwr(Q_PCIE_INTR_ENABLE, 0u);   /* ath10k_pci_irq_disable: step 3 may have switched it on */
		bwr(Q_PCIE_INTR_CLR, Q_INTR_FW_AND_CE);
	}
	wr32(gDbi, 0x04, rd32(gDbi, 0x04) & 0xFFFBu);
	if (gChipGone) {
		A_LOG("done: root port bus mastering off (rp command %08x); chip left alone", rd32(gDbi, 0x04));
		return ok;
	}
	if (!ok) {
		dump_chip("end");
	}
	wr32(gConf, 0x04, rd32(gConf, 0x04) & 0xFFFBu);
	bwr(Q_SOC_WAKE, 0u);
	A_LOG("done: bus mastering off (chip command %08x, rp command %08x), SoC wake released", rd32(gConf, 0x04),
	    rd32(gDbi, 0x04));
	return ok;
}

