static inline uint32_t
rd32(volatile uint32_t *b, uint32_t off)
{
	return b[off / 4];
}

static inline void
wr32(volatile uint32_t *b, uint32_t off, uint32_t v)
{
	b[off / 4] = v;
	A_DSB();
}

static inline uint32_t
brd(uint32_t off)
{
	return rd32(gB, off);
}

static inline void
bwr(uint32_t off, uint32_t v)
{
	wr32(gB, off, v);
}

static inline uint32_t *
dma_words(uint32_t off)
{
	return (uint32_t *)(void *)(gDma + off);
}

/* Clean + invalidate the block's cacheable alias once, before only the non-cacheable one is used. */
static void
cache_flush(const void *va, uint32_t size)
{
	uintptr_t a = (uintptr_t)va & ~(uintptr_t)63u;
	uintptr_t end = ((uintptr_t)va + size + 63u) & ~(uintptr_t)63u;
	A_DSB();
	for (; a < end; a += 64u) {
		A_DC_CIVAC(a);
	}
	A_DSB();
}

/* The DMA block is non-cacheable: ordering is all that is needed, CPU stores before a doorbell write and the
 * descriptor's nbytes before the data it covers. */
static inline void
dma_fence(void)
{
	A_DSB();
}

