#!/usr/bin/env python3
"""Embed the QCA6174 Wi-Fi firmware in the kernel build without putting it in git.

Reads, if present:
  firmware/qca6174/firmware-6.bin   ath10k's QCA6174 hw3.0 firmware from linux-firmware
                                    (ath10k/QCA6174/hw3.0/firmware-6.bin, decompressed if it came as .zst/.xz)
  firmware/qca6174/bdwlan30.bin     this phone's board data (calibration), from its Android firmware
and writes xnu/xnu-4903.270.47/iokit/Kernel/arm/op2_wifi_fw.h, which OP2Ath10k.cpp includes when it exists.
Both paths are gitignored: the firmware is Qualcomm's and stays out of the public repository.
Without the two files the header is removed and Wi-Fi step 2c (wifi=4) reports that no firmware is built in.
Run by tools/build-xnu.sh before every kernel build; touches OP2Ath10k.cpp when the header changes so an
incremental build recompiles it.
"""
import hashlib
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.environ.get("OP2_WIFI_FW_DIR", os.path.join(ROOT, "firmware", "qca6174"))
ARM = os.environ.get("OP2_WIFI_FW_OUT_DIR", os.path.join(ROOT, "xnu", "xnu-4903.270.47", "iokit", "Kernel", "arm"))
OUT = os.path.join(ARM, "op2_wifi_fw.h")
CPP = os.path.join(ARM, "OP2Ath10k.cpp")
MAGIC = b"QCA-ATH10K\x00"


def touch(path):
    if os.path.exists(path):
        os.utime(path, None)


def fw_version(data):
    off = (len(MAGIC) + 3) & ~3
    while off + 8 <= len(data):
        ie_id, ie_len = struct.unpack_from("<II", data, off)
        if ie_id == 0:
            raw = data[off + 8:off + 8 + ie_len].split(b"\x00")[0]
            return "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "?" for c in raw.decode("latin-1"))
        off += 8 + ((ie_len + 3) & ~3)
    return "?"


def c_array(name, data):
    out = ["static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 20):
        out.append("\t" + ",".join("0x%02x" % b for b in bytearray(data[i:i + 20])) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    fw_path = os.path.join(SRC, "firmware-6.bin")
    bd_path = os.path.join(SRC, "bdwlan30.bin")
    if not (os.path.isfile(fw_path) and os.path.isfile(bd_path)):
        if os.path.exists(OUT):
            os.remove(OUT)
            touch(CPP)
        print("[wifi-fw] no firmware/qca6174/firmware-6.bin + bdwlan30.bin: Wi-Fi step 2c will report it")
        return 0
    with open(fw_path, "rb") as f:
        fw = f.read()
    with open(bd_path, "rb") as f:
        bd = f.read()
    if not fw.startswith(MAGIC):
        sys.stderr.write("[wifi-fw] %s is not an ath10k firmware container (still compressed? zstd -d / xz -d)\n" % fw_path)
        return 1
    if not 4096 <= len(bd) <= 8192:
        sys.stderr.write("[wifi-fw] %s is %d bytes; QCA6174 board data is 8124\n" % (bd_path, len(bd)))
        return 1
    version = fw_version(fw)
    text = "\n".join([
        "/* Generated by tools/gen-wifi-fw.py from firmware/qca6174/ - not in git (see .gitignore). */",
        "/* firmware-6.bin %s, %d bytes, sha256 %s */" % (version, len(fw), hashlib.sha256(fw).hexdigest()),
        "/* bdwlan30.bin %d bytes, sha256 %s */" % (len(bd), hashlib.sha256(bd).hexdigest()),
        "#define OP2_WIFI_FW_VERSION \"%s\"" % version,
        "static const uint32_t kOp2WifiFwLen = %du;" % len(fw),
        c_array("kOp2WifiFw", fw),
        "static const uint32_t kOp2WifiBoardLen = %du;" % len(bd),
        c_array("kOp2WifiBoard", bd),
        "",
    ])
    old = None
    if os.path.exists(OUT):
        with open(OUT, "r") as f:
            old = f.read()
    if old != text:
        with open(OUT, "w") as f:
            f.write(text)
        touch(CPP)
    print("[wifi-fw] embedding firmware %s (%d bytes) and board data (%d bytes)" % (version, len(fw), len(bd)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
