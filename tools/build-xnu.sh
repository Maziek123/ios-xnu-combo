#!/usr/bin/env bash
#
# Build script for XNU-4903 on OnePlus 2 (MSM8994) using Xcode 10.3 toolchain.
#
set -o errexit
set -o pipefail

source "$(cd "$(dirname "$0")" && pwd)/env.sh"
op2_require_xcode || exit 1

# Wi-Fi firmware for step 2c (wifi=5): embedded from the gitignored firmware/qca6174/ when present.
python3 "${REPO_ROOT}/tools/gen-wifi-fw.py"

# op2shell (USB shell, SSH, configd services for USB and Wi-Fi) built into the kernel: at every boot
# bsd/kern/op2_shell_sync.c overwrites the phone's /usr/local/bin/op2-air-run with it when they differ, so a plain
# `fastboot boot` keeps the phone's copy current. Rebuilt first when its source is newer (tools/build-op2shell.sh:
# needs the dash, toybox and dropbear builds); without out/shell/build/op2shell the kernel carries none.
SHELL_BIN="${REPO_ROOT}/out/shell/build/op2shell"
if [ "${REPO_ROOT}/userland/op2shell/op2shell.c" -nt "$SHELL_BIN" ]; then
	bash "${REPO_ROOT}/tools/build-op2shell.sh" >/dev/null ||
		echo "[op2shell] not rebuilt (tools/build-op2shell.sh failed); embedding the previous build if there is one" >&2
fi
python3 -I - "$SHELL_BIN" "${XNU_SRC}/bsd/kern/op2_shell_blob.h" <<'PYEOF'
import hashlib, os, sys
src, hdr = sys.argv[1], sys.argv[2]
if not os.path.isfile(src):
    if os.path.exists(hdr):
        os.remove(hdr)
    print("[op2shell] no out/shell/build/op2shell: the kernel carries no op2shell (the phone keeps its own)")
    sys.exit(0)
if '"' in src or '\\' in src:
    sys.exit("[op2shell] path has a quote or backslash: " + src)
data = open(src, 'rb').read()
sha = hashlib.sha256(data).hexdigest()
text = ('/* generated by tools/build-xnu.sh from out/shell/build/op2shell; gitignored */\n'
        '#define OP2_SHELL_BLOB_PATH "%s"\n#define OP2_SHELL_BLOB_LEN %uu\n#define OP2_SHELL_BLOB_SHA "%s"\n'
        % (os.path.abspath(src), len(data), sha[:16]))
if not os.path.exists(hdr) or open(hdr).read() != text:
    open(hdr, 'w').write(text)
note = '' if len(data) <= 16 << 20 else ' (WARNING: bigger than the 16 MiB slot on the phone; the file grows)'
print("[op2shell] embedding op2shell: %u bytes, sha256 %s%s" % (len(data), sha[:16], note))
PYEOF
TOOLCHAIN="${XCODE_ROOT}/Toolchains/XcodeDefault.xctoolchain/usr/bin"
SDK="${XCODE_ROOT}/Platforms/MacOSX.platform/Developer/SDKs/MacOSX10.14.sdk"

export PATH=/opt/local/bin:/usr/local/bin:"${REPO_ROOT}/tools:${TOOLCHAIN}:/usr/bin:/bin:/usr/sbin:/sbin"
unset DEVELOPER_DIR
export XCRUN="${REPO_ROOT}/tools/xcrun"

BUILD_DIR="${XNU_SRC}/BUILD"
mkdir -p "${BUILD_DIR}/obj" "${BUILD_DIR}/dst"

echo "[BUILD] Starting serial XNU build (-j1) for DEVELOPMENT_ARM64_MSM8994..."
make -C "${XNU_SRC}" \
  -j1 \
  MAKEJOBS="--jobs=1" \
  VERBOSE=YES \
  SRCROOT="${XNU_SRC}" \
  OBJROOT="${BUILD_DIR}/obj" \
  DSTROOT="${BUILD_DIR}/dst" \
  SDKROOT="${SDK}" \
  ARCH_CONFIGS=ARM64 \
  KERNEL_CONFIGS=DEVELOPMENT \
  MACHINE_CONFIGS=MSM8994 \
  ARCH_STRING_FOR_CURRENT_MACHINE_CONFIG=arm64 \
  XCRUN="${REPO_ROOT}/tools/xcrun" \
  BUILD_LTO=0 \
  DO_CTFCONVERT=0 \
  DO_CTFMERGE=0 \
  "$@" 2>&1 | tee "${REPO_ROOT}/build.log"
