#!/usr/bin/env bash
#
# Build script for XNU-4903 on OnePlus 2 (MSM8994) using Xcode 10.3 toolchain.
#
set -o errexit
set -o pipefail

source "$(cd "$(dirname "$0")" && pwd)/env.sh"
op2_require_xcode || exit 1

# Wi-Fi firmware for step 2c (wifi=5): embedded from the gitignored firmware/qca6174/ when present.
python3 "${REPO_ROOT}/tools/gen-wifi-fw.py"

# Helper programs built into the kernel; at every boot bsd/kern/op2_shell_sync.c writes each to the phone when it
# differs, so a plain `fastboot boot` keeps them current:
#  - op2shell (USB shell, SSH, configd services) over /usr/local/bin/op2-air-run, if the phone has it. Rebuilt first
#    when its source is newer (tools/build-op2shell.sh: needs dash, toybox and dropbear; tools/build-shell-all.sh).
#  - op2netd (only the configd services that give iOS its route and DNS on wl0/ue0) as /usr/sbin/op2netd, started
#    in place of wifid. Built here from userland/op2netd with the Xcode SDK; needs nothing else.
SHELL_BIN="${REPO_ROOT}/out/shell/build/op2shell"
if [ "${REPO_ROOT}/userland/op2shell/op2shell.c" -nt "$SHELL_BIN" ] ||
   [ "${REPO_ROOT}/userland/op2shell/op2_publish.h" -nt "$SHELL_BIN" ]; then
	bash "${REPO_ROOT}/tools/build-op2shell.sh" >/dev/null 2>&1 ||
		echo "[op2shell] not rebuilt (needs the dash, toybox and dropbear builds: docs/SETUP.md 4); optional, op2netd covers the network"
fi
NETD_BIN="${REPO_ROOT}/out/op2netd/op2netd"
mkdir -p "${REPO_ROOT}/out/op2netd"
if [ "${REPO_ROOT}/userland/op2netd/op2netd.c" -nt "$NETD_BIN" ] ||
   [ "${REPO_ROOT}/userland/op2shell/op2_publish.h" -nt "$NETD_BIN" ]; then
if clang -target arm64-apple-ios12.0 -isysroot "$IPHONEOS_SDK" -O2 -Wall -Wextra \
	-framework SystemConfiguration -framework CoreFoundation \
	-o "$NETD_BIN.tmp" "${REPO_ROOT}/userland/op2netd/op2netd.c" &&
   strip -x "$NETD_BIN.tmp" && codesign -s - -i com.op2.netd --force "$NETD_BIN.tmp"; then
	mv "$NETD_BIN.tmp" "$NETD_BIN"
else
	rm -f "$NETD_BIN.tmp"
	echo "[op2netd] build failed (above); the kernel carries the previous build if there is one" >&2
fi
fi
python3 -I - "${XNU_SRC}/bsd/kern" "$SHELL_BIN" op2shell OP2_SHELL "$NETD_BIN" op2netd OP2_NETD <<'PYEOF'
import hashlib, os, sys
kern, rest = sys.argv[1], sys.argv[2:]
for src, name, macro in zip(rest[0::3], rest[1::3], rest[2::3]):
    hdr = os.path.join(kern, name.replace('op2shell', 'op2_shell').replace('op2netd', 'op2_netd') + '_blob.h')
    if not os.path.isfile(src):
        if os.path.exists(hdr):
            os.remove(hdr)
        print("[%s] none built (%s): the kernel carries no %s" % (name, src, name))
        continue
    if '"' in src or '\\' in src:
        sys.exit("[%s] path has a quote or backslash: %s" % (name, src))
    data = open(src, 'rb').read()
    sha = hashlib.sha256(data).hexdigest()[:16]
    text = ('/* generated by tools/build-xnu.sh from %s; gitignored */\n'
            '#define %s_BLOB_PATH "%s"\n#define %s_BLOB_LEN %uu\n#define %s_BLOB_SHA "%s"\n'
            % (os.path.basename(src), macro, os.path.abspath(src), macro, len(data), macro, sha))
    if not os.path.exists(hdr) or open(hdr).read() != text:
        open(hdr, 'w').write(text)
    note = '' if name != 'op2shell' or len(data) <= 16 << 20 else ' (WARNING: bigger than the 16 MiB slot)'
    print("[%s] embedding %s: %u bytes, sha256 %s%s" % (name, name, len(data), sha, note))
PYEOF
TOOLCHAIN="${XCODE_ROOT}/Toolchains/XcodeDefault.xctoolchain/usr/bin"
SDK="${XCODE_ROOT}/Platforms/MacOSX.platform/Developer/SDKs/MacOSX10.14.sdk"

export PATH=/opt/local/bin:/usr/local/bin:"${REPO_ROOT}/tools:${TOOLCHAIN}:/usr/bin:/bin:/usr/sbin:/sbin"
unset DEVELOPER_DIR
export XCRUN="${REPO_ROOT}/tools/xcrun"

BUILD_DIR="${XNU_SRC}/BUILD"
mkdir -p "${BUILD_DIR}/obj" "${BUILD_DIR}/dst"

echo "[BUILD] Starting serial XNU build (-j1) for DEVELOPMENT_ARM64_MSM8994..."
make -C "${XNU_SRC}" \
  -j1 \
  MAKEJOBS="--jobs=1" \
  VERBOSE=YES \
  SRCROOT="${XNU_SRC}" \
  OBJROOT="${BUILD_DIR}/obj" \
  DSTROOT="${BUILD_DIR}/dst" \
  SDKROOT="${SDK}" \
  ARCH_CONFIGS=ARM64 \
  KERNEL_CONFIGS=DEVELOPMENT \
  MACHINE_CONFIGS=MSM8994 \
  ARCH_STRING_FOR_CURRENT_MACHINE_CONFIG=arm64 \
  XCRUN="${REPO_ROOT}/tools/xcrun" \
  BUILD_LTO=0 \
  DO_CTFCONVERT=0 \
  DO_CTFMERGE=0 \
  "$@" 2>&1 | tee "${REPO_ROOT}/build.log"
